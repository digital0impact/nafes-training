function arrowH(g: G, x1: number, x2: number, y: number, color: string) {
  const d = Math.sign(x2 - x1)
  g.strokeStyle = color
  g.fillStyle = color
  g.lineWidth = 4
  g.beginPath()
  g.moveTo(x1, y)
  g.lineTo(x2 - d * 8, y)
  g.stroke()
  g.beginPath()
  g.moveTo(x2, y)
  g.lineTo(x2 - d * 12, y - 7)
  g.lineTo(x2 - d * 12, y + 7)
  g.closePath()
  g.fill()
}

/** كتلتان صخريتان مع مستوى صدع مائل؛ dy إزاحة الكتلة اليمنى (المعلقة) */
function blocks(g: G, dy: number, dx: number) {
  const layers = ["#c08a4b", "#a9713a", "#8d5a2b", "#704521"]
  // الكتلة اليسرى (الحائط السفلي)
  for (let i = 0; i < 4; i++) {
    g.fillStyle = layers[i]
    g.beginPath()
    g.moveTo(20, 80 + i * 25)
    g.lineTo(150 - i * 12, 80 + i * 25)
    g.lineTo(138 - i * 12, 105 + i * 25)
    g.lineTo(20, 105 + i * 25)
    g.closePath()
    g.fill()
  }
  // الكتلة اليمنى (الحائط العلوي) تتحرك على مستوى الصدع
  g.save()
  g.translate(dx, dy)
  for (let i = 0; i < 4; i++) {
    g.fillStyle = layers[i]
    g.beginPath()
    g.moveTo(156 - i * 12, 80 + i * 25)
    g.lineTo(280, 80 + i * 25)
    g.lineTo(280, 105 + i * 25)
    g.lineTo(144 - i * 12, 105 + i * 25)
    g.closePath()
    g.fill()
  }
  g.restore()
}

