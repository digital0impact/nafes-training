/** السيزموجراف: خط تسجيل يتحرك وقمة كبيرة */
function trace(g: G, ph: number, amp: number, color: string) {
  g.strokeStyle = color
  g.lineWidth = 2
  g.beginPath()
  for (let x = 20; x <= 280; x += 2) {
    const c = ((x + ph * 40) % 260) - 130
    const e = Math.exp(-(c * c) / 600)
    const y = 100 + Math.sin(x * 0.7 + ph * 8) * (3 + amp * e)
    if (x === 20) g.moveTo(x, y)
    else g.lineTo(x, y)
  }
  g.stroke()
}
