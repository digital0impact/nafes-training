function wave(g: G, ph: number, k: number, color: string, amp = 30) {
  g.strokeStyle = color
  g.lineWidth = 3
  g.beginPath()
  for (let x = 15; x <= 285; x += 2) {
    const y = 100 + Math.sin(x * k - ph * 4) * amp
    if (x === 15) g.moveTo(x, y)
    else g.lineTo(x, y)
  }
  g.stroke()
}

const radio: Draw = (g, ph) => {
  bg(g, "#2b1036", "#12061a")
  wave(g, ph * 0.5, 0.02, "#da77f2", 40)
}
const micro: Draw = (g, ph) => {
  bg(g, "#3b230d", "#170e05")
  wave(g, ph * 0.7, 0.045, "#ffa94d")
}
const infrared: Draw = (g, ph) => {
  bg(g, "#3b0d16", "#16050a")
  wave(g, ph, 0.075, "#ff6b6b")
}
const visible: Draw = (g, ph) => {
  bg(g, "#0b1026", "#05070f")
  const cols = ["#e03131", "#f76707", "#fab005", "#40c057", "#1c7ed6", "#4c6ef5", "#7048e8"]
  cols.forEach((c, i) => {
    g.strokeStyle = c
    g.lineWidth = 6
    g.beginPath()
    g.moveTo(40, 100)
    g.lineTo(260, 40 + i * 20 + Math.sin(ph * 2) * 2)
    g.stroke()
  })
  g.fillStyle = "rgba(255,255,255,.85)"
  g.beginPath()
  g.moveTo(40, 70)
  g.lineTo(80, 130)
  g.lineTo(0, 130)
  g.closePath()
  g.fill()
}
const uv: Draw = (g, ph) => {
  bg(g, "#1d1036", "#0b061a")
  wave(g, ph * 1.4, 0.16, "#9775fa", 22)
}
const xray: Draw = (g, ph) => {
  bg(g, "#0d2b3b", "#05141d")
  g.strokeStyle = "#e9ecef"
  g.lineWidth = 8
  g.lineCap = "round"
  g.beginPath()
  g.moveTo(100, 50)
  g.lineTo(200, 150)
  g.stroke()
  for (const [x, y] of [[100, 50], [200, 150]]) {
    g.beginPath()
    g.arc(x - 6, y - 6, 8, 0, 7)
    g.arc(x + 6, y + 6, 8, 0, 7)
    g.fillStyle = "#e9ecef"
    g.fill()
  }
  g.globalAlpha = 0.3 + 0.2 * Math.sin(ph * 3)
  g.fillStyle = "#74c0fc"
  g.fillRect(0, 0, 300, 200)
  g.globalAlpha = 1
}
const gamma: Draw = (g, ph) => {
  bg(g, "#0d3b1a", "#05170a")
  wave(g, ph * 2, 0.32, "#69db7c", 16)
}

/** قصر النظر وطول النظر */
function eye(g: G, ph: number, focusX: number, color: string, top: string) {
  bg(g, top, "#0a0f18")
  g.fillStyle = "#f8f9fa"
  g.beginPath()
  g.arc(170, 100, 70, 0, 7)
  g.fill()
  g.fillStyle = "#74c0fc"
  g.beginPath()
  g.ellipse(102, 100, 10, 30, 0, 0, 7)
  g.fill()
  g.strokeStyle = "#ff8787"
  g.lineWidth = 6
  g.beginPath()
  g.arc(170, 100, 70, -0.9, 0.9)
  g.stroke()
  g.strokeStyle = color
  g.lineWidth = 2.5
  for (const dy of [-22, 0, 22]) {
    g.beginPath()
    g.moveTo(10, 100 + dy)
    g.lineTo(102, 100 + dy)
    g.lineTo(focusX, 100)
    g.stroke()
  }
  g.fillStyle = "#ffe066"
  g.beginPath()
  g.arc(focusX, 100, 4 + Math.sin(ph * 4) * 1.5, 0, 7)
  g.fill()
}
const myopia: Draw = (g, ph) => eye(g, ph, 195, "#4dabf7", "#13283f")
const hyperopia: Draw = (g, ph) => eye(g, ph, 268, "#ffa94d", "#3b230d")

