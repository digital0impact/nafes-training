/** حجر غير منتظم الشكل */
function stone(g: G, cx: number, cy: number, r: number, color: string, seed: number) {
  g.fillStyle = color
  g.beginPath()
  for (let i = 0; i <= 12; i++) {
    const a = (i / 12) * Math.PI * 2
    const rr = r * (0.8 + 0.2 * Math.sin(seed + i * 2.7))
    const x = cx + Math.cos(a) * rr * 1.25
    const y = cy + Math.sin(a) * rr
    if (i === 0) g.moveTo(x, y)
    else g.lineTo(x, y)
  }
  g.closePath()
  g.fill()
}

/** نقاط ثابتة داخل الحجر */
function speckle(g: G, cx: number, cy: number, r: number, n: number, size: number, colors: string[]) {
  for (let i = 0; i < n; i++) {
    const a = Math.sin(i * 12.9898) * 43758.5453
    const b = Math.sin(i * 78.233) * 12345.678
    const fx = a - Math.floor(a)
    const fy = b - Math.floor(b)
    const x = cx + (fx - 0.5) * r * 2
    const y = cy + (fy - 0.5) * r * 1.4
    g.fillStyle = colors[i % colors.length]
    g.fillRect(x, y, size, size)
  }
}

/** نارية: لابة تبرد */
const igneous: Draw = (g, ph) => {
  bg(g, "#3b0d16", "#16050a")
  const glow = 0.5 + 0.5 * Math.sin(ph * 2)
  stone(g, 150, 110, 70, "#343a40", 1)
  g.strokeStyle = `rgba(255,${120 + 60 * glow},40,${0.6 + 0.4 * glow})`
  g.lineWidth = 4
  g.beginPath()
  g.moveTo(90, 90)
  g.lineTo(130, 115)
  g.lineTo(150, 95)
  g.lineTo(190, 130)
  g.lineTo(215, 110)
  g.stroke()
}

/** رسوبية: طبقات وصدفة */
const sedimentary: Draw = (g, ph) => {
  bg(g, "#2b2510", "#141005")
  const cols = ["#e9c46a", "#d4a373", "#bc8a5f", "#a98467", "#ddb892"]
  for (let i = 0; i < 5; i++) {
    g.fillStyle = cols[i]
    g.beginPath()
    g.moveTo(30, 50 + i * 24)
    for (let x = 30; x <= 270; x += 10) g.lineTo(x, 50 + i * 24 + Math.sin(x * 0.04 + i) * 3)
    g.lineTo(270, 74 + i * 24)
    g.lineTo(30, 74 + i * 24)
    g.closePath()
    g.fill()
  }
  // صدفة أحفورية
  g.strokeStyle = "#7f5539"
  g.lineWidth = 2
  g.beginPath()
  for (let t = 0; t < 12; t += 0.2) {
    const r = 2 + t * 1.3
    const x = 200 + Math.cos(t + ph * 0.2) * r
    const y = 110 + Math.sin(t + ph * 0.2) * r
    if (t === 0) g.moveTo(x, y)
    else g.lineTo(x, y)
  }
  g.stroke()
}

/** متحولة: ضغط من الجانبين وطبقات متموجة */
const metamorphic: Draw = (g, ph) => {
  bg(g, "#2b1036", "#12061a")
  const sq = Math.sin(ph * 1.5) * 6
  for (let i = 0; i < 7; i++) {
    g.strokeStyle = i % 2 ? "#e9ecef" : "#495057"
    g.lineWidth = 7
    g.beginPath()
    for (let x = 70 + sq; x <= 230 - sq; x += 4) {
      const y = 60 + i * 13 + Math.sin(x * 0.08 + i * 0.5) * (6 + sq)
      if (x === 70 + sq) g.moveTo(x, y)
      else g.lineTo(x, y)
    }
    g.stroke()
  }
  for (const [x1, x2] of [[20, 60 + sq], [280, 240 - sq]]) {
    g.fillStyle = "#ffa94d"
    g.beginPath()
    g.moveTo(x2, 100)
    g.lineTo(x1, 85)
    g.lineTo(x1, 115)
    g.closePath()
    g.fill()
  }
  g.fillStyle = `rgba(255,107,107,${0.25 + 0.2 * Math.sin(ph * 3)})`
  g.fillRect(70, 170, 160, 12)
}

