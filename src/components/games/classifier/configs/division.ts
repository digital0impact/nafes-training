const fission: Draw = (g, ph) => {
  bg(g, "#2b1a3b", "#120a1c")
  const sep = 24 + 22 * ((Math.sin(ph * 1.2) + 1) / 2)
  for (const s of [-1, 1]) {
    g.fillStyle = "#9775fa"
    g.beginPath()
    g.roundRect(150 + s * sep - 30, 82, 60, 36, 18)
    g.fill()
    g.strokeStyle = "#e5dbff"
    g.lineWidth = 1.5
    g.beginPath()
    g.moveTo(150 + s * sep - 10, 96)
    g.quadraticCurveTo(150 + s * sep, 108, 150 + s * sep + 10, 96)
    g.stroke()
  }
}

