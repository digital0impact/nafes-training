const PAIRS = ["#ff8787", "#74c0fc", "#ffd43b", "#b197fc"]

function chromo(g: G, x: number, y: number, c: string, rot = 0, double = true) {
  g.save()
  g.translate(x, y)
  g.rotate(rot)
  g.strokeStyle = c
  g.lineWidth = 4
  g.lineCap = "round"
  for (const d of double ? [-2.5, 2.5] : [0]) {
    g.beginPath()
    g.moveTo(d, -9)
    g.lineTo(d, 9)
    g.stroke()
  }
  if (double) {
    g.fillStyle = "#fff"
    g.beginPath()
    g.arc(0, 0, 2, 0, 7)
    g.fill()
  }
  g.restore()
}

function cellOutline(g: G, ph: number, cx = 150, cy = 100, rx = 96, ry = 72) {
  blob(g, cx, cy, rx, ry, ph, 2, 5)
  g.fillStyle = "rgba(150,242,215,.18)"
  g.fill()
  g.strokeStyle = "#c3fae8"
  g.lineWidth = 2.5
  g.stroke()
}

function spindle(g: G, y0: number, y1: number, x0: number, x1: number, alpha = 0.45) {
  g.strokeStyle = "rgba(255,255,255," + alpha + ")"
  g.lineWidth = 1
  for (let k = -3; k <= 3; k++) {
    g.beginPath()
    g.moveTo(x0, 100)
    g.quadraticCurveTo(150, 100 + k * 16, x1, 100)
    g.stroke()
  }
  void y0
  void y1
}

/** أطوار الانقسام المتساوي */
const prophase: Draw = (g, ph) => {
  bg(g, "#0f2e2a", "#071816")
  motes(g, ph, "#96f2d7", 6)
  cellOutline(g, ph)
  // الغشاء النووي يتلاشى
  g.setLineDash([4, 6])
  g.strokeStyle = "rgba(255,255,255," + (0.4 + 0.3 * Math.sin(ph * 2)) + ")"
  g.lineWidth = 2
  g.beginPath()
  g.arc(150, 100, 40, 0, 7)
  g.stroke()
  g.setLineDash([])
  PAIRS.forEach((c, i) => chromo(g, 132 + (i % 2) * 34, 86 + Math.floor(i / 2) * 28, c, i * 0.7 + Math.sin(ph + i) * 0.2))
  // المريكزات تتحرك نحو الأقطاب
  const d = 40 + 30 * ((Math.sin(ph) + 1) / 2)
  g.fillStyle = "#ffe066"
  for (const s of [-1, 1]) {
    g.beginPath()
    g.arc(150 + s * d, 100, 4, 0, 7)
    g.fill()
  }
}

const metaphase: Draw = (g, ph) => {
  bg(g, "#0f2e2a", "#071816")
  cellOutline(g, ph)
  spindle(g, 0, 0, 62, 238)
  PAIRS.forEach((c, i) => chromo(g, 150 + Math.sin(ph * 3 + i) * 1.5, 64 + i * 24, c, Math.PI / 2))
  g.fillStyle = "#ffe066"
  for (const x of [62, 238]) {
    g.beginPath()
    g.arc(x, 100, 4, 0, 7)
    g.fill()
  }
}

const anaphase: Draw = (g, ph) => {
  bg(g, "#0f2e2a", "#071816")
  cellOutline(g, ph, 150, 100, 104, 68)
  spindle(g, 0, 0, 54, 246)
  const sep = 18 + 50 * ((Math.sin(ph * 1.5) + 1) / 2)
  PAIRS.forEach((c, i) => {
    for (const s of [-1, 1]) {
      g.save()
      g.translate(150 + s * sep, 64 + i * 24)
      g.strokeStyle = c
      g.lineWidth = 4
      g.lineCap = "round"
      g.beginPath()
      g.moveTo(s * 5, -8)
      g.lineTo(-s * 3, 0)
      g.lineTo(s * 5, 8)
      g.stroke()
      g.restore()
    }
  })
}

const telophase: Draw = (g, ph) => {
  bg(g, "#0f2e2a", "#071816")
  const pinch = 0.35 + 0.25 * ((Math.sin(ph) + 1) / 2)
  // خليتان تتخصران في المنتصف
  for (const s of [-1, 1]) {
    blob(g, 150 + s * 56, 100, 60, 62 * (1 - pinch * 0.2), ph, 2, 5)
    g.fillStyle = "rgba(150,242,215,.18)"
    g.fill()
    g.strokeStyle = "#c3fae8"
    g.lineWidth = 2.5
    g.stroke()
    g.strokeStyle = "rgba(255,255,255,.7)"
    g.lineWidth = 2
    g.beginPath()
    g.arc(150 + s * 62, 100, 24, 0, 7)
    g.stroke()
    PAIRS.forEach((c, i) => chromo(g, 140 + s * 62 + (i % 2) * 18, 92 + Math.floor(i / 2) * 16, c, i, false))
  }
}

/** متساوٍ أم منصف: عدد الخلايا الناتجة */
function result(n: number, half: boolean): Draw {
  return (g, ph) => {
    bg(g, n === 2 ? "#13283f" : "#2b1640", n === 2 ? "#0a1626" : "#14091f")
    // الخلية الأم
    blob(g, 46, 100, 30, 30, ph, 1.5, 5)
    g.fillStyle = "rgba(255,255,255,.12)"
    g.fill()
    g.strokeStyle = "#fff"
    g.lineWidth = 2
    g.stroke()
    PAIRS.forEach((c, i) => chromo(g, 38 + (i % 2) * 16, 92 + Math.floor(i / 2) * 16, c, 0.3, false))
    g.strokeStyle = "rgba(255,255,255,.6)"
    g.lineWidth = 2
    g.beginPath()
    g.moveTo(84, 100)
    g.lineTo(110, 100)
    g.stroke()
    const pos = n === 2 ? [[170, 60], [170, 140]] : [[150, 50], [230, 50], [150, 150], [230, 150]]
    pos.forEach(([x, y], k) => {
      const s = 1 + 0.05 * Math.sin(ph * 2 + k)
      blob(g, x, y, 32 * s, 30 * s, ph + k, 1.5, 5)
      g.fillStyle = "rgba(255,255,255,.12)"
      g.fill()
      g.strokeStyle = "#fff"
      g.lineWidth = 2
      g.stroke()
      const list = half ? PAIRS.slice(k % 2, (k % 2) + 2) : PAIRS
      list.forEach((c, i) => chromo(g, x - 8 + (i % 2) * 16, y - 8 + Math.floor(i / 2) * 16, c, 0.3, false))
    })
  }
}

