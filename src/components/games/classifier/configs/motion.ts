function road(g: G) {
  g.fillStyle = "#343a40"
  g.fillRect(0, 140, 300, 40)
  g.fillStyle = "#ffe066"
  for (let i = 0; i < 6; i++) g.fillRect(10 + i * 52, 158, 28, 4)
}

function car(g: G, x: number, color: string) {
  g.fillStyle = color
  g.beginPath()
  g.roundRect(x - 30, 118, 60, 20, 6)
  g.fill()
  g.beginPath()
  g.roundRect(x - 18, 104, 34, 18, 6)
  g.fill()
  g.fillStyle = "#212529"
  for (const dx of [-17, 17]) {
    g.beginPath()
    g.arc(x + dx, 140, 7, 0, 7)
    g.fill()
  }
}

function vec(g: G, x1: number, y1: number, x2: number, y2: number, color: string, w = 4) {
  const a = Math.atan2(y2 - y1, x2 - x1)
  g.strokeStyle = color
  g.fillStyle = color
  g.lineWidth = w
  g.beginPath()
  g.moveTo(x1, y1)
  g.lineTo(x2 - 8 * Math.cos(a), y2 - 8 * Math.sin(a))
  g.stroke()
  g.beginPath()
  g.moveTo(x2, y2)
  g.lineTo(x2 - 14 * Math.cos(a - 0.45), y2 - 14 * Math.sin(a - 0.45))
  g.lineTo(x2 - 14 * Math.cos(a + 0.45), y2 - 14 * Math.sin(a + 0.45))
  g.closePath()
  g.fill()
}

/** مسار متعرج طوله هو المسافة */
const scalar: Draw = (g, ph) => {
  bg(g, "#2b2510", "#141005")
  g.strokeStyle = "#ffd43b"
  g.lineWidth = 4
  g.setLineDash([8, 6])
  g.lineDashOffset = -ph * 20
  g.beginPath()
  g.moveTo(40, 150)
  g.bezierCurveTo(60, 20, 150, 200, 180, 70)
  g.bezierCurveTo(200, 10, 260, 60, 260, 150)
  g.stroke()
  g.setLineDash([])
  for (const [x, y] of [[40, 150], [260, 150]]) {
    g.fillStyle = "#fff"
    g.beginPath()
    g.arc(x, y, 6, 0, 7)
    g.fill()
  }
}

/** سهم مستقيم من البداية إلى النهاية: الإزاحة */
const vector: Draw = (g, ph) => {
  bg(g, "#102a3b", "#06141d")
  g.strokeStyle = "rgba(255,255,255,.18)"
  g.lineWidth = 2
  g.beginPath()
  g.moveTo(40, 150)
  g.bezierCurveTo(60, 20, 150, 200, 180, 70)
  g.bezierCurveTo(200, 10, 260, 60, 260, 150)
  g.stroke()
  const k = 0.6 + 0.4 * ((Math.sin(ph * 1.5) + 1) / 2)
  vec(g, 40, 150, 40 + 220 * k, 150, "#4dabf7", 5)
}

const positive: Draw = (g, ph) => {
  bg(g, "#0d3b1a", "#05170a")
  road(g)
  const t = (ph * 0.35) % 1
  car(g, 40 + 230 * t * t, "#51cf66")
  vec(g, 120, 60, 220, 60, "#69db7c")
}
const zero: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  road(g)
  const t = (ph * 0.2) % 1
  car(g, 30 + 240 * t, "#4dabf7")
  g.fillStyle = "#a5d8ff"
  g.fillRect(110, 56, 80, 6)
}
const negative: Draw = (g, ph) => {
  bg(g, "#3b0d16", "#16050a")
  road(g)
  const t = (ph * 0.35) % 1
  car(g, 40 + 230 * (1 - (1 - t) * (1 - t)), "#ff6b6b")
  vec(g, 220, 60, 120, 60, "#ff8787")
}

/** راكب يندفع للأمام عند توقف السيارة */
const inertia: Draw = (g, ph) => {
  bg(g, "#2b1036", "#12061a")
  road(g)
  car(g, 150, "#9775fa")
  const k = Math.max(0, Math.sin(ph * 1.5))
  g.fillStyle = "#ffd8a8"
  g.beginPath()
  g.arc(150 + k * 30, 92 - k * 6, 9, 0, 7)
  g.fill()
  g.fillStyle = "#c92a2a"
  g.fillRect(200, 100, 12, 40)
}

/** شاحنة ثقيلة متحركة: صعوبة الإيقاف */
const momentum: Draw = (g, ph) => {
  bg(g, "#3b230d", "#170e05")
  road(g)
  const x = 60 + ((ph * 30) % 200)
  g.fillStyle = "#fd7e14"
  g.beginPath()
  g.roundRect(x - 50, 96, 70, 42, 6)
  g.fill()
  g.beginPath()
  g.roundRect(x + 22, 108, 28, 30, 6)
  g.fill()
  g.fillStyle = "#212529"
  for (const dx of [-35, 0, 35]) {
    g.beginPath()
    g.arc(x + dx, 140, 8, 0, 7)
    g.fill()
  }
  g.fillStyle = "#fff"
  g.font = "bold 18px sans-serif"
  g.textAlign = "center"
  g.direction = "rtl"
  g.fillText("خ = ك × ع", 150, 50)
  g.direction = "inherit"
}

/** كرتان متساويتان تتصادمان وترتدان */
const conserve: Draw = (g, ph) => {
  bg(g, "#0d2b3b", "#05141d")
  const t = Math.abs(Math.sin(ph * 0.9))
  const d = 30 + t * 90
  for (const [s, c] of [[-1, "#e8590c"], [1, "#e8590c"]] as const) {
    const grd = g.createRadialGradient(150 + s * d - 6, 94, 3, 150 + s * d, 100, 28)
    grd.addColorStop(0, "#ffc078")
    grd.addColorStop(1, c)
    g.fillStyle = grd
    g.beginPath()
    g.arc(150 + s * d, 100, 28, 0, 7)
    g.fill()
  }
  g.fillStyle = "#fff"
  g.font = "bold 16px sans-serif"
  g.textAlign = "center"
  g.direction = "rtl"
  g.fillText("مجموع الزخم ثابت", 150, 175)
  g.direction = "inherit"
}

