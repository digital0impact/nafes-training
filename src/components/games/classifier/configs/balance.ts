function tree(g: G, x: number, y: number, s: number, c = "#2f9e44") {
  g.fillStyle = "#8d5a2b"
  g.fillRect(x - 4 * s, y - 30 * s, 8 * s, 30 * s)
  g.fillStyle = c
  g.beginPath()
  g.arc(x, y - 40 * s, 22 * s, 0, 7)
  g.fill()
}
function blob(g: G, x: number, y: number, r: number, c: string) {
  g.fillStyle = c
  g.beginPath()
  g.arc(x, y, r, 0, 7)
  g.fill()
}

