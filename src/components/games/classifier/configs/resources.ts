function sunAt(g: G, x: number, y: number, r: number, ph: number) {
  g.fillStyle = "#ffd43b"
  g.beginPath()
  g.arc(x, y, r, 0, 7)
  g.fill()
  g.strokeStyle = "#ffe066"
  g.lineWidth = 3
  for (let i = 0; i < 8; i++) {
    const a = (i * Math.PI) / 4 + ph * 0.5
    g.beginPath()
    g.moveTo(x + Math.cos(a) * (r + 4), y + Math.sin(a) * (r + 4))
    g.lineTo(x + Math.cos(a) * (r + 12), y + Math.sin(a) * (r + 12))
    g.stroke()
  }
}
function turbine(g: G, x: number, y: number, s: number, ph: number) {
  g.strokeStyle = "#f1f3f5"
  g.lineWidth = 3
  g.beginPath()
  g.moveTo(x, y)
  g.lineTo(x, y + 90 * s)
  g.stroke()
  for (let i = 0; i < 3; i++) {
    const a = ph * 2 + (i * Math.PI * 2) / 3
    g.lineWidth = 5 * s
    g.beginPath()
    g.moveTo(x, y)
    g.lineTo(x + Math.cos(a) * 38 * s, y + Math.sin(a) * 38 * s)
    g.stroke()
  }
}

