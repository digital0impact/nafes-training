/** خريطة مبسطة للجدول الدوري (١٨ مجموعة × ٧ دورات + سلسلتان) مع إبراز منطقة */
function table(g: G, ph: number, on: (c: number, r: number) => boolean, color: string) {
  const W = 14.4
  const H = 16
  const x0 = 20
  const y0 = 20
  const exists = (c: number, r: number) => {
    if (r === 0) return c === 0 || c === 17
    if (r === 1 || r === 2) return c <= 1 || c >= 12
    return true
  }
  const pulse = 0.75 + 0.25 * Math.sin(ph * 3)
  for (let r = 0; r < 7; r++)
    for (let c = 0; c < 18; c++) {
      if (!exists(c, r)) continue
      const hit = on(c, r)
      g.fillStyle = hit ? color : "rgba(255,255,255,.12)"
      g.globalAlpha = hit ? pulse : 1
      g.fillRect(x0 + c * W, y0 + r * H, W - 2, H - 2)
    }
  for (let r = 0; r < 2; r++)
    for (let c = 0; c < 14; c++) {
      const hit = on(-1, 7 + r)
      g.fillStyle = hit ? color : "rgba(255,255,255,.12)"
      g.globalAlpha = hit ? pulse : 1
      g.fillRect(x0 + (c + 3) * W, y0 + 8 * H + 6 + r * H, W - 2, H - 2)
    }
  g.globalAlpha = 1
}

const region = (pred: (c: number, r: number) => boolean, color: string, top: string): Draw => (g, ph) => {
  bg(g, top, "#0a0f18")
  table(g, ph, pred, color)
}

const representative = region((c, r) => r < 7 && (c <= 1 || c >= 12), "#ffd43b", "#2b2510")
const transition = region((c, r) => r >= 3 && r < 7 && c >= 2 && c <= 11, "#4dabf7", "#102a3b")
const innerTransition = region((_c, r) => r >= 7, "#e599f7", "#2b1036")
const alkali = region((c, r) => c === 0 && r >= 1 && r < 7, "#ff6b6b", "#3b0d16")
const alkalineEarth = region((c, r) => c === 1 && r >= 1 && r < 7, "#ffa94d", "#3b230d")
const halogens = region((c, r) => c === 16 && r >= 1 && r < 7, "#69db7c", "#0d3b1a")
const noble = region((c, r) => c === 17 && r < 7, "#74c0fc", "#0d233b")

/** فلز، لافلز، شبه فلز */
const metal: Draw = (g, ph) => {
  bg(g, "#1b1d2e", "#0d0e18")
  // سلك فلزي لامع ينثني (قابل للطرق والسحب)
  const grd = g.createLinearGradient(40, 0, 260, 0)
  grd.addColorStop(0, "#adb5bd")
  grd.addColorStop(0.5 + 0.3 * Math.sin(ph), "#f8f9fa")
  grd.addColorStop(1, "#868e96")
  g.strokeStyle = grd
  g.lineWidth = 12
  g.lineCap = "round"
  g.beginPath()
  g.moveTo(40, 120)
  g.quadraticCurveTo(150, 120 - 50 * Math.sin(ph * 0.8), 260, 120)
  g.stroke()
  g.fillStyle = "rgba(255,255,255,.8)"
  g.beginPath()
  g.arc(150 + Math.sin(ph) * 60, 100, 3, 0, 7)
  g.fill()
}
const nonmetal: Draw = (g, ph) => {
  bg(g, "#2e2416", "#140f08")
  // كتلة كبريت صفراء هشة تتشقق
  g.fillStyle = "#fcc419"
  g.beginPath()
  g.moveTo(90, 150)
  g.lineTo(110, 70)
  g.lineTo(190, 60)
  g.lineTo(215, 140)
  g.closePath()
  g.fill()
  g.strokeStyle = "#5c4022"
  g.lineWidth = 2
  const k = (Math.sin(ph) + 1) / 2
  g.beginPath()
  g.moveTo(150, 62)
  g.lineTo(145, 100)
  g.lineTo(160, 120 + k * 20)
  g.stroke()
  for (let i = 0; i < 4; i++) {
    g.fillStyle = "#fab005"
    g.beginPath()
    g.arc(120 + i * 25, 170 + Math.sin(ph + i) * 2, 4, 0, 7)
    g.fill()
  }
}
const metalloid: Draw = (g, ph) => {
  bg(g, "#102a3b", "#06141d")
  // رقاقة سليكون (شبه موصل)
  g.fillStyle = "#495057"
  g.fillRect(100, 60, 100, 80)
  g.strokeStyle = "#adb5bd"
  g.lineWidth = 2
  for (let i = 0; i < 6; i++) {
    g.beginPath()
    g.moveTo(108 + i * 16, 60)
    g.lineTo(108 + i * 16, 48)
    g.moveTo(108 + i * 16, 140)
    g.lineTo(108 + i * 16, 152)
    g.stroke()
  }
  g.strokeStyle = "rgba(116,192,252," + (0.5 + 0.5 * Math.sin(ph * 3)) + ")"
  g.beginPath()
  g.moveTo(110, 100)
  g.lineTo(140, 80)
  g.lineTo(170, 120)
  g.lineTo(190, 90)
  g.stroke()
}

