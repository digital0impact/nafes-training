function arrowTo(g: G, x1: number, y1: number, x2: number, y2: number, color: string) {
  const a = Math.atan2(y2 - y1, x2 - x1)
  g.strokeStyle = color
  g.fillStyle = color
  g.lineWidth = 3
  g.beginPath()
  g.moveTo(x1, y1)
  g.lineTo(x2, y2)
  g.stroke()
  g.beginPath()
  g.moveTo(x2, y2)
  g.lineTo(x2 - 9 * Math.cos(a - 0.5), y2 - 9 * Math.sin(a - 0.5))
  g.lineTo(x2 - 9 * Math.cos(a + 0.5), y2 - 9 * Math.sin(a + 0.5))
  g.closePath()
  g.fill()
}

function flask(g: G, liquid: string) {
  g.fillStyle = liquid
  g.beginPath()
  g.moveTo(118, 120)
  g.lineTo(90, 170)
  g.lineTo(210, 170)
  g.lineTo(182, 120)
  g.closePath()
  g.fill()
  g.strokeStyle = "rgba(255,255,255,.85)"
  g.lineWidth = 3
  g.beginPath()
  g.moveTo(135, 40)
  g.lineTo(135, 90)
  g.lineTo(88, 172)
  g.lineTo(212, 172)
  g.lineTo(165, 90)
  g.lineTo(165, 40)
  g.stroke()
}

