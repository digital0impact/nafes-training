function factory(g: G, x: number, ph: number, smoke: string) {
  g.fillStyle = "#495057"
  g.fillRect(x, 120, 70, 50)
  g.fillRect(x + 10, 80, 14, 40)
  g.fillRect(x + 40, 90, 14, 30)
  for (let i = 0; i < 5; i++) {
    const t = (ph * 0.4 + i / 5) % 1
    g.fillStyle = smoke
    g.globalAlpha = 0.6 * (1 - t)
    g.beginPath()
    g.arc(x + 17 + t * 40, 75 - t * 60, 8 + t * 14, 0, 7)
    g.fill()
  }
  g.globalAlpha = 1
}

const smog: Draw = (g, ph) => {
  bg(g, "#5c5f66", "#2b2d31")
  g.fillStyle = "#343a40"
  for (let i = 0; i < 6; i++) g.fillRect(20 + i * 45, 110 - (i % 3) * 20, 35, 90)
  g.fillStyle = `rgba(173,181,189,${0.45 + 0.15 * Math.sin(ph)})`
  g.fillRect(0, 60, 300, 140)
  const grd = g.createRadialGradient(240, 40, 3, 240, 40, 25)
  grd.addColorStop(0, "rgba(255,212,59,.8)")
  grd.addColorStop(1, "rgba(255,212,59,0)")
  g.fillStyle = grd
  g.fillRect(200, 0, 80, 80)
}
