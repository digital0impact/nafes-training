function box(g: G) {
  g.strokeStyle = "rgba(255,255,255,.8)"
  g.lineWidth = 3
  g.strokeRect(70, 30, 160, 140)
}

function particle(g: G, x: number, y: number, c: string, r = 7) {
  g.fillStyle = c
  g.beginPath()
  g.arc(x, y, r, 0, 7)
  g.fill()
}

const solid: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  box(g)
  for (let r = 0; r < 6; r++)
    for (let c = 0; c < 7; c++)
      particle(g, 92 + c * 20 + Math.sin(ph * 9 + r * 3 + c) * 1.5, 62 + r * 20 + Math.cos(ph * 9 + c * 2 + r) * 1.5, "#74c0fc")
}

const liquid: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  box(g)
  for (let i = 0; i < 30; i++) {
    const x = 84 + ((i * 37 + ph * 14 * (1 + (i % 3))) % 132)
    const y = 104 + ((i * 23) % 60) + Math.sin(ph * 2 + i) * 3
    particle(g, x, y, "#4dabf7")
  }
}

const gas: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  box(g)
  for (let i = 0; i < 12; i++) {
    const tx = (i * 0.37 + ph * 0.35 * (1 + (i % 4) * 0.4)) % 2
    const ty = (i * 0.61 + ph * 0.27 * (1 + (i % 3) * 0.5)) % 2
    const x = 80 + 140 * (tx < 1 ? tx : 2 - tx)
    const y = 40 + 120 * (ty < 1 ? ty : 2 - ty)
    particle(g, x, y, "#a5d8ff")
  }
}

const plasma: Draw = (g, ph) => {
  bg(g, "#2b0d3b", "#12061c")
  // نجم متوهج: أيونات وإلكترونات
  const grd = g.createRadialGradient(150, 100, 6, 150, 100, 70)
  grd.addColorStop(0, "#fff3bf")
  grd.addColorStop(0.5, "#ff922b")
  grd.addColorStop(1, "rgba(255,146,43,0)")
  g.fillStyle = grd
  g.beginPath()
  g.arc(150, 100, 70 + Math.sin(ph * 3) * 4, 0, 7)
  g.fill()
  for (let i = 0; i < 14; i++) {
    const a = ph * (0.8 + (i % 3) * 0.3) + i
    const r = 30 + (i % 5) * 12
    particle(g, 150 + Math.cos(a) * r, 100 + Math.sin(a) * r, i % 2 ? "#ffd43b" : "#e599f7", i % 2 ? 4 : 2.5)
  }
}

const crystalline: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  // شبكة منتظمة ثلاثية الأبعاد (مكعبات ملح)
  for (let r = 0; r < 4; r++)
    for (let c = 0; c < 5; c++) {
      const x = 60 + c * 46 + Math.sin(ph * 6 + r + c) * 0.8
      const y = 40 + r * 38
      g.strokeStyle = "rgba(255,255,255,.35)"
      g.lineWidth = 1.5
      if (c < 4) {
        g.beginPath()
        g.moveTo(x, y)
        g.lineTo(x + 46, y)
        g.stroke()
      }
      if (r < 3) {
        g.beginPath()
        g.moveTo(x, y)
        g.lineTo(x, y + 38)
        g.stroke()
      }
      particle(g, x, y, (r + c) % 2 ? "#e9ecef" : "#69db7c", (r + c) % 2 ? 9 : 6)
    }
}

const amorphous: Draw = (g, ph) => {
  bg(g, "#2e2416", "#140f08")
  const rnd = (n: number) => {
    const v = Math.sin(n * 12.9898) * 43758.5453
    return v - Math.floor(v)
  }
  for (let i = 0; i < 26; i++) {
    const x = 50 + rnd(i + 1) * 200 + Math.sin(ph * 6 + i) * 0.8
    const y = 36 + rnd(i + 101) * 130
    particle(g, x, y, i % 3 ? "#ffa94d" : "#e9ecef", i % 3 ? 7 : 5)
  }
}

const viscosity: Draw = (g, ph) => {
  bg(g, "#3b2a0d", "#1a1206")
  // سائل لزج ينساب ببطء من ملعقة
  g.fillStyle = "#adb5bd"
  g.beginPath()
  g.ellipse(150, 40, 40, 14, 0, 0, 7)
  g.fill()
  const len = 30 + ((ph * 18) % 100)
  g.fillStyle = "#f59f00"
  g.beginPath()
  g.moveTo(144, 46)
  g.quadraticCurveTo(146, 46 + len / 2, 147, 46 + len)
  g.lineTo(153, 46 + len)
  g.quadraticCurveTo(154, 46 + len / 2, 156, 46)
  g.closePath()
  g.fill()
  g.beginPath()
  g.ellipse(150, 46 + len, 7, 6, 0, 0, 7)
  g.fill()
  g.fillStyle = "#e67700"
  g.beginPath()
  g.ellipse(150, 176, 60, 10, 0, 0, 7)
  g.fill()
}

const tension: Draw = (g, ph) => {
  bg(g, "#0d2a3b", "#061620")
  g.fillStyle = "#1971c2"
  g.fillRect(0, 110, 300, 90)
  // سطح الماء ينحني تحت أرجل حشرة
  const x0 = 150 + Math.sin(ph * 0.5) * 60
  g.strokeStyle = "#a5d8ff"
  g.lineWidth = 2
  g.beginPath()
  for (let x = 0; x <= 300; x += 4) {
    let y = 110
    for (const dx of [-26, -10, 10, 26]) y += 5 * Math.exp(-((x - x0 - dx) ** 2) / 30)
    g.lineTo(x, y)
  }
  g.stroke()
  g.fillStyle = "#212529"
  g.beginPath()
  g.ellipse(x0, 94, 14, 6, 0, 0, 7)
  g.fill()
  g.strokeStyle = "#212529"
  g.lineWidth = 1.5
  for (const dx of [-26, -10, 10, 26]) {
    g.beginPath()
    g.moveTo(x0 + dx * 0.4, 96)
    g.lineTo(x0 + dx, 112)
    g.stroke()
  }
  // إبرة طافية
  g.strokeStyle = "#ced4da"
  g.lineWidth = 2
  g.beginPath()
  g.moveTo(40, 111)
  g.lineTo(100, 111)
  g.stroke()
}

/** تحولات المادة: سهم بين حالتين */
function change(from: string, to: string, color: string): Draw {
  return (g, ph) => {
    bg(g, "#1b1d2e", "#0d0e18")
    const drawState = (s: string, x: number) => {
      g.strokeStyle = "rgba(255,255,255,.7)"
      g.lineWidth = 2
      g.strokeRect(x - 40, 60, 80, 80)
      for (let i = 0; i < 9; i++) {
        let px = x - 24 + (i % 3) * 24
        let py = 76 + Math.floor(i / 3) * 24
        if (s === "l") {
          px = x - 28 + ((i * 7 + ph * 12 * (1 + (i % 2))) % 56)
          py = 100 + (i % 3) * 12 + Math.sin(ph * 2 + i) * 2
        }
        if (s === "g") {
          const h1 = Math.sin((i + 1) * 12.9898) * 43758.5453
          const h2 = Math.sin((i + 51) * 12.9898) * 43758.5453
          px = x - 30 + (((h1 - Math.floor(h1)) * 60 + ph * 30) % 60)
          py = 66 + (((h2 - Math.floor(h2)) * 68 + ph * 20) % 68)
        }
        particle(g, px, py, color, 5)
      }
    }
    // من اليمين إلى اليسار، كما يُقرأ السهم في العربية
    drawState(from, 230)
    drawState(to, 70)
    g.fillStyle = "#ffe27a"
    const t = (ph * 0.8) % 1
    g.beginPath()
    g.moveTo(176 - t * 30, 92)
    g.lineTo(154 - t * 30, 100)
    g.lineTo(176 - t * 30, 108)
    g.closePath()
    g.fill()
  }
}

