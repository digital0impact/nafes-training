import { bg } from "../kit"
import type { CardDef, ClassifierConfig, Draw, G } from "../types"

function stars(g: G, ph: number) {
  for (let i = 0; i < 26; i++) {
    const a = Math.sin(i * 91.7) * 1000
    const b = Math.sin(i * 37.3) * 1000
    g.fillStyle = `rgba(255,255,255,${0.3 + 0.3 * Math.sin(ph * 2 + i)})`
    g.fillRect((a - Math.floor(a)) * 300, (b - Math.floor(b)) * 200, 1.5, 1.5)
  }
}
function sun(g: G, x: number, y: number, r: number) {
  const grd = g.createRadialGradient(x, y, r * 0.2, x, y, r * 1.6)
  grd.addColorStop(0, "#fff3bf")
  grd.addColorStop(0.45, "#ffd43b")
  grd.addColorStop(1, "rgba(255,146,43,0)")
  g.fillStyle = grd
  g.beginPath()
  g.arc(x, y, r * 1.6, 0, 7)
  g.fill()
}
function earth(g: G, x: number, y: number, r: number, spin = 0) {
  g.fillStyle = "#1c7ed6"
  g.beginPath()
  g.arc(x, y, r, 0, 7)
  g.fill()
  g.save()
  g.beginPath()
  g.arc(x, y, r, 0, 7)
  g.clip()
  g.fillStyle = "#40c057"
  for (let i = 0; i < 3; i++) {
    const cx = x - r + ((spin * r + i * r * 0.9) % (r * 2.6))
    g.beginPath()
    g.ellipse(cx, y - r * 0.2 + i * r * 0.3, r * 0.35, r * 0.22, 0.4, 0, 7)
    g.fill()
  }
  g.restore()
}
function moon(g: G, x: number, y: number, r: number, dark = false) {
  g.fillStyle = dark ? "#5c3a2e" : "#dee2e6"
  g.beginPath()
  g.arc(x, y, r, 0, 7)
  g.fill()
}

/** دوران الأرض حول محورها: نصف مضيء ونصف مظلم */
const rotation: Draw = (g, ph) => {
  bg(g, "#0b1026", "#05070f")
  stars(g, ph)
  earth(g, 150, 100, 55, ph * 0.6)
  g.fillStyle = "rgba(0,0,20,.55)"
  g.beginPath()
  g.arc(150, 100, 55, Math.PI / 2, (Math.PI * 3) / 2)
  g.fill()
  g.strokeStyle = "#ced4da"
  g.lineWidth = 2
  g.beginPath()
  g.moveTo(135, 30)
  g.lineTo(165, 170)
  g.stroke()
  g.strokeStyle = "#ff6b6b"
  g.lineWidth = 3
  g.beginPath()
  g.ellipse(150, 100, 70, 14, 0.2, 0.3, Math.PI - 0.3)
  g.stroke()
}
/** دوران الأرض حول الشمس في مدار */
const revolution: Draw = (g, ph) => {
  bg(g, "#0b1026", "#05070f")
  stars(g, ph)
  g.strokeStyle = "rgba(255,255,255,.25)"
  g.lineWidth = 1.5
  g.beginPath()
  g.ellipse(150, 100, 115, 70, 0, 0, 7)
  g.stroke()
  sun(g, 150, 100, 22)
  const a = ph * 0.5
  earth(g, 150 + Math.cos(a) * 115, 100 + Math.sin(a) * 70, 13, ph)
}
/** القمر يدور حول الأرض ويظهر بأطوار */
const moonPanel: Draw = (g, ph) => {
  bg(g, "#0b1026", "#05070f")
  stars(g, ph)
  earth(g, 150, 100, 26, ph * 0.3)
  g.strokeStyle = "rgba(255,255,255,.2)"
  g.beginPath()
  g.arc(150, 100, 70, 0, 7)
  g.stroke()
  const a = ph * 0.6
  const mx = 150 + Math.cos(a) * 70
  const my = 100 + Math.sin(a) * 70
  moon(g, mx, my, 12)
  g.fillStyle = "rgba(0,0,20,.7)"
  g.beginPath()
  g.arc(mx, my, 12, -Math.PI / 2, Math.PI / 2)
  g.fill()
}

/** كسوف الشمس: الشمس ثم القمر ثم الأرض */
const solarEclipse: Draw = (g, ph) => {
  bg(g, "#0b1026", "#05070f")
  sun(g, 40, 100, 34)
  g.fillStyle = "rgba(0,0,0,.45)"
  g.beginPath()
  g.moveTo(160, 92)
  g.lineTo(250, 85)
  g.lineTo(250, 115)
  g.lineTo(160, 108)
  g.closePath()
  g.fill()
  moon(g, 160, 100 + Math.sin(ph) * 3, 9)
  earth(g, 250, 100, 26, ph * 0.3)
}
/** خسوف القمر: الشمس ثم الأرض ثم القمر */
const lunarEclipse: Draw = (g, ph) => {
  bg(g, "#0b1026", "#05070f")
  sun(g, 40, 100, 34)
  earth(g, 165, 100, 26, ph * 0.3)
  g.fillStyle = "rgba(0,0,0,.45)"
  g.beginPath()
  g.moveTo(170, 76)
  g.lineTo(270, 88)
  g.lineTo(270, 112)
  g.lineTo(170, 124)
  g.closePath()
  g.fill()
  moon(g, 255, 100 + Math.sin(ph) * 3, 11, true)
}
/** مد مرتفع: الشمس والقمر والأرض على خط مستقيم */
const springTide: Draw = (g, ph) => {
  bg(g, "#0b2a3b", "#05141d")
  sun(g, 35, 100, 30)
  const k = 1 + 0.08 * Math.sin(ph * 2)
  g.fillStyle = "rgba(77,171,247,.55)"
  g.beginPath()
  g.ellipse(180, 100, 50 * k, 32, 0, 0, 7)
  g.fill()
  earth(g, 180, 100, 26, ph * 0.3)
  moon(g, 265, 100, 10)
}
/** مد منخفض: زاوية قائمة */
const neapTide: Draw = (g, ph) => {
  bg(g, "#1d2433", "#0b0f18")
  sun(g, 35, 100, 30)
  const k = 1 + 0.05 * Math.sin(ph * 2)
  g.fillStyle = "rgba(77,171,247,.45)"
  g.beginPath()
  g.ellipse(180, 100, 34, 40 * k, 0, 0, 7)
  g.fill()
  earth(g, 180, 100, 26, ph * 0.3)
  moon(g, 180, 30, 10)
  g.strokeStyle = "rgba(255,255,255,.4)"
  g.setLineDash([4, 4])
  g.beginPath()
  g.moveTo(60, 100)
  g.lineTo(180, 100)
  g.lineTo(180, 30)
  g.stroke()
  g.setLineDash([])
}

