const echo: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  g.fillStyle = "#868e96"
  g.fillRect(260, 30, 20, 150)
  for (let i = 0; i < 3; i++) {
    const t = (ph * 0.35 + i / 3) % 1
    const x = t < 0.5 ? 40 + t * 2 * 210 : 250 - (t - 0.5) * 2 * 210
    g.strokeStyle = t < 0.5 ? "rgba(255,212,59,.8)" : "rgba(116,192,252,.8)"
    g.lineWidth = 3
    g.beginPath()
    g.arc(x, 105, 22, t < 0.5 ? -0.8 : Math.PI - 0.8, t < 0.5 ? 0.8 : Math.PI + 0.8)
    g.stroke()
  }
  g.fillStyle = "#ffd8a8"
  g.beginPath()
  g.arc(30, 90, 10, 0, 7)
  g.fill()
  g.fillRect(24, 100, 12, 40)
}

