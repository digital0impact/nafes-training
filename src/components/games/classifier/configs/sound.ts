function sine(g: G, ph: number, amp: number, k: number, color: string, y = 100, w = 3) {
  g.strokeStyle = color
  g.lineWidth = w
  g.beginPath()
  for (let x = 15; x <= 285; x += 3) {
    const yy = y + Math.sin(x * k - ph * 4) * amp
    if (x === 15) g.moveTo(x, yy)
    else g.lineTo(x, yy)
  }
  g.stroke()
}

const transverse: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  sine(g, ph, 40, 0.045, "#74c0fc")
  for (let i = 0; i < 9; i++) {
    const x = 30 + i * 30
    g.fillStyle = "#ffe066"
    g.beginPath()
    g.arc(x, 100 + Math.sin(x * 0.045 - ph * 4) * 40, 4, 0, 7)
    g.fill()
  }
}
const longitudinal: Draw = (g, ph) => {
  bg(g, "#0d3b1a", "#05170a")
  g.strokeStyle = "#8ce99a"
  g.lineWidth = 2
  for (let i = 0; i < 34; i++) {
    const x0 = 15 + i * 8
    const x = x0 + Math.sin(x0 * 0.06 - ph * 4) * 7
    g.beginPath()
    g.ellipse(x, 100, 3, 34, 0, 0, 7)
    g.stroke()
  }
}
const em: Draw = (g, ph) => {
  bg(g, "#2b1036", "#12061a")
  sine(g, ph, 35, 0.05, "#ff8787", 100, 2.5)
  g.save()
  g.translate(0, 0)
  g.globalAlpha = 0.8
  g.strokeStyle = "#74c0fc"
  g.lineWidth = 2.5
  g.beginPath()
  for (let x = 15; x <= 285; x += 3) {
    const s = Math.sin(x * 0.05 - ph * 4)
    const xx = x + s * 12
    const yy = 100 + s * 6
    if (x === 15) g.moveTo(xx, yy)
    else g.lineTo(xx, yy)
  }
  g.stroke()
  g.restore()
}
const combined: Draw = (g, ph) => {
  bg(g, "#3b230d", "#170e05")
  g.fillStyle = "#8d5a2b"
  g.fillRect(0, 130, 300, 70)
  sine(g, ph, 18, 0.07, "#ffa94d", 130, 4)
  for (let i = 0; i < 4; i++) {
    const r = ((ph * 30 + i * 25) % 100) + 5
    g.strokeStyle = `rgba(255,169,77,${1 - r / 105})`
    g.lineWidth = 2
    g.beginPath()
    g.arc(150, 190, r, Math.PI, 0)
    g.stroke()
  }
}

/** خصائص الموجة */
const wavelength: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  sine(g, ph * 0.2, 35, 0.0471, "#74c0fc")
  g.strokeStyle = "#ffe066"
  g.lineWidth = 3
  const x1 = 15 + ((Math.PI / 2 + ph * 0.8) / 0.0471) % 133.4
  g.beginPath()
  g.moveTo(x1, 50)
  g.lineTo(x1 + 133.4, 50)
  g.stroke()
  g.fillStyle = "#ffe066"
  g.fillRect(x1 - 1.5, 44, 3, 12)
  g.fillRect(x1 + 132, 44, 3, 12)
}
const frequency: Draw = (g, ph) => {
  bg(g, "#2b2510", "#141005")
  sine(g, ph * 2, 30, 0.12, "#ffd43b")
}
const amplitude: Draw = (g, ph) => {
  bg(g, "#3b0d16", "#16050a")
  const a = 25 + 25 * Math.abs(Math.sin(ph * 0.6))
  sine(g, ph, a, 0.045, "#ff8787")
  g.strokeStyle = "rgba(255,255,255,.5)"
  g.setLineDash([4, 4])
  g.beginPath()
  g.moveTo(15, 100)
  g.lineTo(285, 100)
  g.stroke()
  g.setLineDash([])
}
const speed: Draw = (g, ph) => {
  bg(g, "#0d3b1a", "#05170a")
  sine(g, ph * 2.5, 30, 0.045, "#8ce99a")
  const x = 20 + ((ph * 80) % 260)
  g.fillStyle = "#fff"
  g.beginPath()
  g.moveTo(x + 12, 160)
  g.lineTo(x, 152)
  g.lineTo(x, 168)
  g.closePath()
  g.fill()
}

