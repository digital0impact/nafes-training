const reflect: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  g.fillStyle = "#adb5bd"
  g.fillRect(40, 160, 220, 8)
  g.setLineDash([4, 4])
  g.strokeStyle = "rgba(255,255,255,.5)"
  g.beginPath()
  g.moveTo(150, 160)
  g.lineTo(150, 40)
  g.stroke()
  g.setLineDash([])
  g.strokeStyle = "#ffd43b"
  g.lineWidth = 3
  g.beginPath()
  g.moveTo(60, 50)
  g.lineTo(150, 160)
  g.lineTo(240, 50)
  g.stroke()
  const t = (ph * 0.4) % 1
  const [x, y] = t < 0.5 ? [60 + t * 2 * 90, 50 + t * 2 * 110] : [150 + (t - 0.5) * 2 * 90, 160 - (t - 0.5) * 2 * 110]
  g.fillStyle = "#fff"
  g.beginPath()
  g.arc(x, y, 5, 0, 7)
  g.fill()
}
