function bar(g: G, x: number, y: number, w: number, left: string, right: string) {
  g.fillStyle = left === "N" ? "#e03131" : "#1c7ed6"
  g.fillRect(x, y - 16, w / 2, 32)
  g.fillStyle = right === "N" ? "#e03131" : "#1c7ed6"
  g.fillRect(x + w / 2, y - 16, w / 2, 32)
  g.direction = "ltr"
  g.fillStyle = "#fff"
  g.font = "bold 16px sans-serif"
  g.textAlign = "center"
  g.textBaseline = "middle"
  g.fillText(left, x + 14, y + 1)
  g.fillText(right, x + w - 14, y + 1)
  g.direction = "inherit"
}

/** أقطاب تتجاذب */
const attract: Draw = (g, ph) => {
  bg(g, "#0d3b1a", "#05170a")
  const d = 10 + Math.abs(Math.sin(ph)) * 30
  bar(g, 150 - d - 100, 100, 100, "S", "N")
  bar(g, 150 + d, 100, 100, "S", "N")
}
/** أقطاب تتنافر */
const repel: Draw = (g, ph) => {
  bg(g, "#3b0d16", "#16050a")
  const d = 20 + Math.abs(Math.sin(ph)) * 20
  bar(g, 150 - d - 100, 100, 100, "S", "N")
  bar(g, 150 + d, 100, 100, "N", "S")
}
/** خطوط المجال حول مغناطيس */
const field: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  g.strokeStyle = "rgba(165,216,255,.6)"
  g.lineWidth = 1.5
  for (let k = 1; k <= 4; k++) {
    g.beginPath()
    g.ellipse(150, 100, 60 + k * 18, k * 18, 0, 0, 7)
    g.stroke()
  }
  for (let k = 1; k <= 4; k++) {
    const a = ph * 0.8 + k
    g.fillStyle = "#ffe066"
    g.beginPath()
    g.arc(150 + Math.cos(a) * (60 + k * 18), 100 + Math.sin(a) * k * 18, 3, 0, 7)
    g.fill()
  }
  bar(g, 100, 100, 100, "S", "N")
}
/** المناطق المغناطيسية */
function domains(g: G, ph: number, aligned: boolean, top: string) {
  bg(g, top, "#0a0f18")
  g.fillStyle = "#495057"
  g.fillRect(40, 40, 220, 120)
  for (let r = 0; r < 3; r++)
    for (let c = 0; c < 5; c++) {
      const cx = 62 + c * 44
      const cy = 62 + r * 38
      const a = aligned ? Math.sin(ph) * 0.08 : Math.sin(r * 7 + c * 13) * 3 + Math.sin(ph + r + c) * 0.2
      g.strokeStyle = aligned ? "#ffe066" : "#ced4da"
      g.fillStyle = aligned ? "#ffe066" : "#ced4da"
      g.lineWidth = 2.5
      g.beginPath()
      g.moveTo(cx - Math.cos(a) * 14, cy - Math.sin(a) * 14)
      g.lineTo(cx + Math.cos(a) * 14, cy + Math.sin(a) * 14)
      g.stroke()
      g.beginPath()
      g.arc(cx + Math.cos(a) * 14, cy + Math.sin(a) * 14, 3.5, 0, 7)
      g.fill()
    }
}
const magnetDomains: Draw = (g, ph) => domains(g, ph, true, "#2b2510")
const ironDomains: Draw = (g, ph) => domains(g, ph, false, "#1d2433")

