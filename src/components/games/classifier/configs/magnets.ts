/** المولد: حركة تتحول إلى كهرباء */
const generator: Draw = (g, ph) => {
  bg(g, "#0d3b1a", "#05170a")
  g.fillStyle = "#e03131"
  g.fillRect(40, 50, 40, 80)
  g.fillStyle = "#1c7ed6"
  g.fillRect(220, 50, 40, 80)
  g.save()
  g.translate(150, 90)
  g.rotate(ph * 2)
  g.strokeStyle = "#ffa94d"
  g.lineWidth = 5
  g.strokeRect(-50, -12, 100, 24)
  g.restore()
  const on = 0.5 + 0.5 * Math.abs(Math.sin(ph * 2))
  const grd = g.createRadialGradient(150, 165, 2, 150, 165, 26)
  grd.addColorStop(0, `rgba(255,236,153,${on})`)
  grd.addColorStop(1, "rgba(255,236,153,0)")
  g.fillStyle = grd
  g.beginPath()
  g.arc(150, 165, 26, 0, 7)
  g.fill()
  g.fillStyle = "#ffe066"
  g.beginPath()
  g.arc(150, 165, 9, 0, 7)
  g.fill()
}
