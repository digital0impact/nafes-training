import { bg } from "../kit"
import type { CardDef, ClassifierConfig, Draw, G } from "../types"

function stars(g: G, ph: number, n = 30) {
  for (let i = 0; i < n; i++) {
    const a = Math.sin(i * 91.7) * 1000
    const b = Math.sin(i * 37.3) * 1000
    g.fillStyle = `rgba(255,255,255,${0.3 + 0.3 * Math.sin(ph * 2 + i)})`
    g.fillRect((a - Math.floor(a)) * 300, (b - Math.floor(b)) * 200, 1.5, 1.5)
  }
}
function planet(g: G, x: number, y: number, r: number, c1: string, c2: string) {
  const grd = g.createRadialGradient(x - r / 3, y - r / 3, r * 0.1, x, y, r)
  grd.addColorStop(0, c1)
  grd.addColorStop(1, c2)
  g.fillStyle = grd
  g.beginPath()
  g.arc(x, y, r, 0, 7)
  g.fill()
}

const inner: Draw = (g, ph) => {
  bg(g, "#0b1026", "#05070f")
  stars(g, ph)
  const grd = g.createRadialGradient(0, 100, 10, 0, 100, 60)
  grd.addColorStop(0, "#fff3bf")
  grd.addColorStop(1, "rgba(255,146,43,0)")
  g.fillStyle = grd
  g.fillRect(0, 30, 70, 140)
  const pl: [number, string, string][] = [[8, "#ced4da", "#868e96"], [13, "#ffe8cc", "#e8590c"], [14, "#74c0fc", "#1864ab"], [11, "#ffa8a8", "#c92a2a"]]
  pl.forEach(([r, a, b], i) => planet(g, 80 + i * 55, 100 + Math.sin(ph + i) * 6, r, a, b))
}
