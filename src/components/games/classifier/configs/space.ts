/** المجرات */
function galaxyDots(g: G, ph: number, fn: (i: number, t: number) => [number, number], n: number, color: string) {
  for (let i = 0; i < n; i++) {
    const [x, y] = fn(i, ph)
    g.fillStyle = color
    g.globalAlpha = 0.3 + 0.7 * ((i % 7) / 7)
    g.fillRect(x, y, 2, 2)
  }
  g.globalAlpha = 1
}
const elliptical: Draw = (g, ph) => {
  bg(g, "#0b1026", "#05070f")
  g.save()
  g.translate(150, 100)
  g.scale(1.4, 0.9)
  g.rotate(ph * 0.05)
  const grd = g.createRadialGradient(0, 0, 3, 0, 0, 70)
  grd.addColorStop(0, "#fff9db")
  grd.addColorStop(0.35, `rgba(255,236,153,${0.55 + 0.15 * Math.sin(ph * 2)})`)
  grd.addColorStop(1, "rgba(0,0,0,0)")
  g.fillStyle = grd
  g.beginPath()
  g.arc(0, 0, 70, 0, 7)
  g.fill()
  g.restore()
}
const spiral: Draw = (g, ph) => {
  bg(g, "#0b1026", "#05070f")
  galaxyDots(
    g,
    ph,
    (i, t) => {
      const arm = i % 2
      const k = (i / 400) * 4.5
      const a = k * 2.2 + arm * Math.PI + t * 0.3
      const r = 6 + k * 18
      const j = Math.sin(i * 7.7) * 5
      return [150 + Math.cos(a) * r + j, 100 + Math.sin(a) * r * 0.75 + j]
    },
    400,
    "#a5d8ff",
  )
  g.fillStyle = "#fff3bf"
  g.beginPath()
  g.arc(150, 100, 8, 0, 7)
  g.fill()
}
const irregular: Draw = (g, ph) => {
  bg(g, "#0b1026", "#05070f")
  galaxyDots(
    g,
    ph,
    (i, t) => {
      const a = Math.sin(i * 12.9898) * 43758.5
      const b = Math.sin(i * 78.233) * 12345.6
      const fx = a - Math.floor(a)
      const fy = b - Math.floor(b)
      return [90 + fx * 120 + Math.sin(t + i) * 2, 60 + fy * 80 + Math.sin(fx * 9) * 15]
    },
    260,
    "#d0bfff",
  )
}

/** مذنب، نيازك، حزام الكويكبات */
const comet: Draw = (g, ph) => {
  bg(g, "#0b1026", "#05070f")
  stars(g, ph)
  const x = 200 + Math.sin(ph * 0.5) * 20
  const y = 80 + Math.cos(ph * 0.5) * 10
  const grd = g.createLinearGradient(x, y, x - 150, y + 60)
  grd.addColorStop(0, "rgba(165,216,255,.9)")
  grd.addColorStop(1, "rgba(165,216,255,0)")
  g.fillStyle = grd
  g.beginPath()
  g.moveTo(x, y - 8)
  g.lineTo(x - 150, y + 40)
  g.lineTo(x - 140, y + 80)
  g.lineTo(x, y + 8)
  g.closePath()
  g.fill()
  g.fillStyle = "#fff"
  g.beginPath()
  g.arc(x, y, 9, 0, 7)
  g.fill()
}
const meteorite: Draw = (g, ph) => {
  bg(g, "#2b1036", "#12061a")
  g.fillStyle = "#1c7ed6"
  g.beginPath()
  g.arc(150, 260, 120, Math.PI, 0)
  g.fill()
  const t = (ph * 0.35) % 1
  const x = 260 - t * 130
  const y = 20 + t * 120
  g.strokeStyle = "rgba(255,169,77,.7)"
  g.lineWidth = 6
  g.beginPath()
  g.moveTo(x + 40, y - 37)
  g.lineTo(x, y)
  g.stroke()
  g.fillStyle = "#868e96"
  g.beginPath()
  g.arc(x, y, 8, 0, 7)
  g.fill()
}
const belt: Draw = (g, ph) => {
  bg(g, "#0b1026", "#05070f")
  g.strokeStyle = "rgba(255,255,255,.12)"
  g.beginPath()
  g.ellipse(150, 100, 130, 75, 0, 0, 7)
  g.stroke()
  for (let i = 0; i < 70; i++) {
    const a = (i / 70) * Math.PI * 2 + ph * 0.15
    const r = 1 + Math.abs(Math.sin(i * 3.3)) * 0.1
    g.fillStyle = "#adb5bd"
    g.fillRect(150 + Math.cos(a) * 112 * r, 100 + Math.sin(a) * 64 * r, 2 + (i % 3), 2 + (i % 2))
  }
  const grd = g.createRadialGradient(150, 100, 3, 150, 100, 26)
  grd.addColorStop(0, "#fff3bf")
  grd.addColorStop(1, "rgba(255,146,43,0)")
  g.fillStyle = grd
  g.beginPath()
  g.arc(150, 100, 26, 0, 7)
  g.fill()
}

