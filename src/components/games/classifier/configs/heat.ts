const lowC: Draw = (g, ph) => {
  bg(g, "#2b2510", "#141005")
  g.fillStyle = "#e9c46a"
  g.fillRect(0, 120, 300, 80)
  g.fillStyle = "#fff"
  g.fillRect(250, 30, 8, 60)
  const h = 20 + ((Math.sin(ph) + 1) / 2) * 35
  g.fillStyle = "#ff6b6b"
  g.fillRect(250, 90 - h, 8, h)
  for (let i = 0; i < 3; i++) {
    g.strokeStyle = `rgba(255,169,77,${0.4 + 0.3 * Math.sin(ph * 3 + i)})`
    g.lineWidth = 3
    g.beginPath()
    for (let y = 115; y > 60; y -= 4) g.lineTo(80 + i * 40 + Math.sin(y * 0.15 + ph * 4 + i) * 5, y)
    g.stroke()
  }
}

