function particles(g: G, ph: number, speed: number, spread: number, color: string) {
  for (let i = 0; i < 14; i++) {
    const cx = 80 + (i % 5) * 35
    const cy = 60 + Math.floor(i / 5) * 40
    const x = cx + Math.sin(ph * speed + i * 2.1) * spread
    const y = cy + Math.cos(ph * speed * 1.3 + i * 1.7) * spread
    g.fillStyle = color
    g.beginPath()
    g.arc(x, y, 8, 0, 7)
    g.fill()
  }
}

const expand: Draw = (g, ph) => {
  bg(g, "#3b0d16", "#16050a")
  particles(g, ph, 4, 14, "#ff8787")
}
const contract: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  particles(g, ph, 1, 3, "#74c0fc")
}

/** طرق انتقال الحرارة */
const conduction: Draw = (g, ph) => {
  bg(g, "#3b230d", "#170e05")
  const grd = g.createLinearGradient(40, 0, 260, 0)
  grd.addColorStop(0, "#ff6b6b")
  grd.addColorStop(1, "#4dabf7")
  g.fillStyle = grd
  g.fillRect(40, 90, 220, 20)
  for (let i = 0; i < 10; i++) {
    g.fillStyle = "#fff"
    g.beginPath()
    g.arc(50 + i * 22 + Math.sin(ph * 6 + i) * (3 - i * 0.25), 100, 3, 0, 7)
    g.fill()
  }
  g.fillStyle = "#ff922b"
  g.beginPath()
  g.ellipse(45, 140, 12, 22 + Math.sin(ph * 8) * 3, 0, 0, 7)
  g.fill()
}
const radiation: Draw = (g, ph) => {
  bg(g, "#2b2510", "#141005")
  const grd = g.createRadialGradient(50, 100, 4, 50, 100, 40)
  grd.addColorStop(0, "#fff3bf")
  grd.addColorStop(1, "rgba(255,146,43,0)")
  g.fillStyle = grd
  g.beginPath()
  g.arc(50, 100, 40, 0, 7)
  g.fill()
  g.strokeStyle = "#ffa94d"
  g.lineWidth = 3
  for (let k = -1; k <= 1; k++) {
    g.beginPath()
    for (let x = 90; x < 250; x += 3) g.lineTo(x, 100 + k * 30 + Math.sin(x * 0.12 - ph * 6) * 7)
    g.stroke()
  }
  g.fillStyle = "#1c7ed6"
  g.beginPath()
  g.arc(270, 100, 22, 0, 7)
  g.fill()
}
const convection: Draw = (g, ph) => {
  bg(g, "#0d2b3b", "#05141d")
  g.strokeStyle = "rgba(255,255,255,.8)"
  g.lineWidth = 3
  g.strokeRect(80, 40, 140, 120)
  g.fillStyle = "rgba(77,171,247,.35)"
  g.fillRect(82, 60, 136, 98)
  for (let i = 0; i < 12; i++) {
    const t = (ph * 0.3 + i / 12) % 1
    const a = t * Math.PI * 2
    const x = 150 + Math.cos(a) * 45
    const y = 108 + Math.sin(a) * 35
    g.fillStyle = Math.cos(a) > 0 ? "#ff8787" : "#74c0fc"
    g.beginPath()
    g.arc(x, y, 4, 0, 7)
    g.fill()
  }
  g.fillStyle = "#ff922b"
  g.beginPath()
  g.ellipse(150, 178, 30, 8 + Math.sin(ph * 8) * 2, 0, 0, 7)
  g.fill()
}

