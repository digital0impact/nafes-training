  g.fillStyle = "#1c7ed6"
  g.fillRect(0, 110, 300, 90)
  for (let i = 0; i < 5; i++) {
    g.strokeStyle = "rgba(165,216,255,.6)"
    g.lineWidth = 2
    g.beginPath()
    for (let x = 0; x < 300; x += 6) g.lineTo(x, 120 + i * 16 + Math.sin(x * 0.05 + ph * 2 + i) * 3)
    g.stroke()
  }
  g.fillStyle = "#fff"
  g.fillRect(250, 30, 8, 60)
  g.fillStyle = "#4dabf7"
  g.fillRect(250, 70, 8, 20)
