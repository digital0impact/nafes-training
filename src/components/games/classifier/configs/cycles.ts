import { bg, curve } from "../kit"
import type { CardDef, ClassifierConfig, G } from "../types"

function sky(g: G) {
  bg(g, "#1c4a6e", "#0d2438")
  g.fillStyle = "#1971c2"
  g.fillRect(0, 160, 160, 40)
  g.fillStyle = "#5c4022"
  g.beginPath()
  g.moveTo(140, 200)
  g.lineTo(160, 160)
  g.lineTo(300, 140)
  g.lineTo(300, 200)
  g.closePath()
  g.fill()
}
function sun(g: G, ph: number, x = 40, y = 34) {
  g.fillStyle = "#ffd43b"
  g.shadowColor = "#ffd43b"
  g.shadowBlur = 14 + Math.sin(ph * 2) * 4
  g.beginPath()
  g.arc(x, y, 16, 0, 7)
  g.fill()
  g.shadowBlur = 0
}
function cloud(g: G, x: number, y: number, s = 1, color = "#e7f5ff") {
  g.fillStyle = color
  for (const [dx, dy, r] of [[-22, 4, 14], [0, -6, 18], [22, 4, 14], [0, 8, 14]]) {
    g.beginPath()
    g.arc(x + dx * s, y + dy * s, r * s, 0, 7)
    g.fill()
  }
}
function vapor(g: G, ph: number, x0: number, x1: number) {
  g.strokeStyle = "rgba(231,245,255,.7)"
  g.lineWidth = 2
  for (let i = 0; i < 5; i++) {
    const t = (ph * 0.3 + i / 5) % 1
    const x = x0 + ((x1 - x0) * i) / 4
    g.globalAlpha = 1 - t
    g.beginPath()
    for (let y = 0; y < 30; y += 3) g.lineTo(x + Math.sin((y + t * 60) * 0.3) * 4, 156 - t * 90 - y)
    g.stroke()
  }
  g.globalAlpha = 1
}
function rain(g: G, ph: number, x0: number, x1: number, y0: number) {
  g.strokeStyle = "#74c0fc"
  g.lineWidth = 2
  for (let i = 0; i < 12; i++) {
    const t = (ph * 0.8 + i * 0.37) % 1
    const x = x0 + ((i * 37) % (x1 - x0))
    const y = y0 + t * (150 - y0)
    g.beginPath()
    g.moveTo(x, y)
    g.lineTo(x - 2, y + 7)
    g.stroke()
  }
}

/* اللوحات: الدورات الثلاث */
function waterCycle(g: G, ph: number) {
  sky(g)
  sun(g, ph)
  vapor(g, ph, 40, 120)
  cloud(g, 200, 50)
  rain(g, ph, 175, 235, 64)
  g.strokeStyle = "rgba(255,255,255,.5)"
  g.lineWidth = 2
  g.setLineDash([5, 5])
  curve(g, [[90, 110], [140, 50], [176, 48]])
  g.stroke()
  g.setLineDash([])
}

function carbonCycle(g: G, ph: number) {
  sky(g)
  sun(g, ph, 260, 30)
  // شجرة تمتص ثاني أكسيد الكربون
  g.fillStyle = "#6b4f2a"
  g.fillRect(212, 110, 10, 40)
  g.fillStyle = "#2f9e44"
  g.beginPath()
  g.arc(217, 100, 28, 0, 7)
  g.fill()
  // مصنع يطلق الدخان (حرق الوقود الأحفوري)
  g.fillStyle = "#495057"
  g.fillRect(60, 120, 50, 40)
  g.fillRect(90, 90, 12, 32)
  for (let i = 0; i < 5; i++) {
    const t = (ph * 0.25 + i / 5) % 1
    g.fillStyle = "rgba(173,181,189," + (0.8 - t * 0.8) + ")"
    g.beginPath()
    g.arc(96 + t * 60, 84 - t * 50, 5 + t * 10, 0, 7)
    g.fill()
  }
  // جزيئات CO2 تتجه نحو الشجرة
  g.font = "bold 11px sans-serif"
  g.textAlign = "center"
  for (let i = 0; i < 3; i++) {
    const t = (ph * 0.2 + i / 3) % 1
    g.fillStyle = "rgba(255,255,255," + (1 - t * 0.6) + ")"
    g.fillText("CO₂", 150 + t * 50, 50 + t * 40)
  }
}

function nitrogenCycle(g: G, ph: number) {
  bg(g, "#20184a", "#0c0a22")
  g.fillStyle = "#5c4022"
  g.fillRect(0, 130, 300, 70)
  // برق يومض
  if (Math.sin(ph * 1.7) > 0.85) {
    g.strokeStyle = "#fff3bf"
    g.lineWidth = 3
    g.beginPath()
    g.moveTo(70, 10)
    g.lineTo(58, 50)
    g.lineTo(76, 50)
    g.lineTo(60, 100)
    g.stroke()
  }
  cloud(g, 70, 18, 1, "#868e96")
  // نبات بقولي بعقد جذرية
  g.strokeStyle = "#51cf66"
  g.lineWidth = 4
  g.beginPath()
  g.moveTo(200, 130)
  g.lineTo(200, 76)
  g.stroke()
  for (const s of [-1, 1]) {
    g.fillStyle = "#40c057"
    g.beginPath()
    g.ellipse(200 + s * 14, 90, 13, 6, s * 0.4, 0, 7)
    g.fill()
  }
  g.strokeStyle = "#e9c46a"
  g.lineWidth = 2
  const roots: [number, number][] = [[180, 176], [200, 186], [222, 172]]
  roots.forEach(([x, y], i) => {
    g.beginPath()
    g.moveTo(200, 130)
    g.quadraticCurveTo((200 + x) / 2, 150, x, y)
    g.stroke()
    g.fillStyle = "#ff8787"
    g.beginPath()
    g.arc((200 + x) / 2 + 4, 156, 4 + Math.sin(ph * 2 + i), 0, 7)
    g.fill()
  })
}

/* اللوحات: مراحل دورة الماء */
function evaporation(g: G, ph: number) {
  sky(g)
  sun(g, ph)
  vapor(g, ph, 20, 140)
}
function condensation(g: G, ph: number) {
  bg(g, "#1c4a6e", "#0d2438")
  const s = 0.9 + 0.15 * Math.sin(ph)
  cloud(g, 150, 90, s * 1.6)
  for (let i = 0; i < 8; i++) {
    const a = (i / 8) * Math.PI * 2 + ph * 0.4
    const r = 90 - ((ph * 20 + i * 10) % 50)
    g.fillStyle = "#a5d8ff"
    g.beginPath()
    g.arc(150 + Math.cos(a) * r, 90 + Math.sin(a) * r * 0.6, 3, 0, 7)
    g.fill()
  }
}
function precipitation(g: G, ph: number) {
  bg(g, "#2b3a4a", "#121b24")
  cloud(g, 100, 40, 1.3, "#adb5bd")
  cloud(g, 210, 46, 1.1, "#adb5bd")
  rain(g, ph, 60, 260, 56)
  g.fillStyle = "#1971c2"
  g.fillRect(0, 160, 300, 40)
}
function groundwater(g: G, ph: number) {
  bg(g, "#1c4a6e", "#0d2438")
  g.fillStyle = "#8d6e3c"
  g.fillRect(0, 70, 300, 130)
  // مسامات التربة والصخور
  for (let r = 0; r < 5; r++)
    for (let c = 0; c < 12; c++) {
      g.fillStyle = "#6b4f2a"
      g.beginPath()
      g.arc(14 + c * 25 + (r % 2) * 12, 90 + r * 22, 8, 0, 7)
      g.fill()
    }
  // ماء يتسرب للأسفل ويتجمع
  for (let i = 0; i < 10; i++) {
    const t = (ph * 0.3 + i / 10) % 1
    g.fillStyle = "#4dabf7"
    g.beginPath()
    g.arc(20 + i * 28, 76 + t * 90, 2.5, 0, 7)
    g.fill()
  }
  g.fillStyle = "rgba(77,171,247,.55)"
  g.fillRect(0, 172, 300, 28)
  // جريان سطحي نحو البحر
  g.strokeStyle = "#74c0fc"
  g.lineWidth = 4
  g.beginPath()
  for (let x = 0; x <= 300; x += 10) g.lineTo(x, 70 + Math.sin(x * 0.05 + ph * 3) * 2)
  g.stroke()
}

