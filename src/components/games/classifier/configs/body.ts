/** صورة ظلية لجسم الإنسان كخلفية لكل جهاز */
function silhouette(g: G) {
  g.fillStyle = "rgba(255,255,255,.07)"
  g.strokeStyle = "rgba(255,255,255,.18)"
  g.lineWidth = 2
  g.beginPath()
  g.arc(150, 26, 17, 0, 7)
  g.fill()
  g.stroke()
  g.beginPath()
  g.moveTo(126, 48)
  g.quadraticCurveTo(150, 42, 174, 48)
  g.lineTo(196, 112)
  g.lineTo(184, 116)
  g.lineTo(172, 82)
  g.lineTo(170, 150)
  g.lineTo(176, 200)
  g.lineTo(156, 200)
  g.lineTo(150, 156)
  g.lineTo(144, 200)
  g.lineTo(124, 200)
  g.lineTo(130, 150)
  g.lineTo(128, 82)
  g.lineTo(116, 116)
  g.lineTo(104, 112)
  g.closePath()
  g.fill()
  g.stroke()
}

function frame(top: string, bottom: string, inner: Draw): Draw {
  return (g, ph) => {
    bg(g, top, bottom)
    motes(g, ph, "#ffffff", 6)
    silhouette(g)
    inner(g, ph)
  }
}

const circulatory = frame("#3b0d16", "#16050a", (g, ph) => {
  const beat = 1 + 0.12 * Math.max(0, Math.sin(ph * 6))
  // أوعية: شرايين حمراء وأوردة زرقاء
  const loops: [string, [number, number][]][] = [
    ["#ff6b6b", [[150, 74], [118, 60], [108, 110], [132, 150], [150, 190]]],
    ["#4dabf7", [[150, 190], [168, 150], [192, 110], [182, 60], [150, 74]]],
  ]
  loops.forEach(([c, pts], k) => {
    g.strokeStyle = c
    g.lineWidth = 3
    curve(g, pts)
    g.stroke()
    for (let i = 0; i < 4; i++) {
      const t = (ph * 0.25 + i / 4 + k * 0.5) % 1
      const seg = Math.min(pts.length - 2, Math.floor(t * (pts.length - 1)))
      const f = t * (pts.length - 1) - seg
      const x = pts[seg][0] + (pts[seg + 1][0] - pts[seg][0]) * f
      const y = pts[seg][1] + (pts[seg + 1][1] - pts[seg][1]) * f
      g.fillStyle = c
      g.beginPath()
      g.arc(x, y, 3, 0, 7)
      g.fill()
    }
  })
  g.save()
  g.translate(154, 78)
  g.scale(beat * 0.42, beat * 0.42)
  g.fillStyle = "#e03131"
  g.beginPath()
  g.moveTo(0, 50)
  g.bezierCurveTo(-80, 6, -54, -56, 0, -22)
  g.bezierCurveTo(54, -56, 80, 6, 0, 50)
  g.fill()
  g.restore()
})

