function pea(g: G, x: number, ph: number, tall: boolean, scale = 1) {
  const h = (tall ? 104 : 46) * scale
  const base = 176
  g.strokeStyle = "#2f9e44"
  g.lineWidth = 4 * scale
  g.lineCap = "round"
  g.beginPath()
  g.moveTo(x, base)
  for (let y = 0; y <= h; y += 6) g.lineTo(x + Math.sin(y * 0.12 + ph) * 3 * scale, base - y)
  g.stroke()
  for (let y = 18; y < h; y += 26 * scale) {
    for (const s of [-1, 1]) {
      g.fillStyle = "#51cf66"
      g.beginPath()
      g.ellipse(x + s * 10 * scale, base - y, 9 * scale, 5 * scale, s * 0.5, 0, 7)
      g.fill()
    }
  }
  g.fillStyle = "#e599f7"
  g.beginPath()
  g.arc(x, base - h - 4 * scale, 6 * scale, 0, 7)
  g.fill()
}

function soil(g: G) {
  bg(g, "#1d3b2a", "#0c1d14")
  g.fillStyle = "#5c4022"
  g.fillRect(0, 176, 300, 24)
}

function letters(g: G, txt: string, color: string, y = 30) {
  g.fillStyle = color
  g.font = "bold 34px sans-serif"
  g.textAlign = "center"
  g.textBaseline = "middle"
  g.fillText(txt, 150, y)
}

const dominant: Draw = (g, ph) => {
  soil(g)
  pea(g, 150, ph, true)
  letters(g, "T", "#ffe27a")
}
const recessive: Draw = (g, ph) => {
  soil(g)
  pea(g, 150, ph, false)
  letters(g, "t", "#a5d8ff")
}
const pure: Draw = (g, ph) => {
  soil(g)
  pea(g, 100, ph, true, 0.85)
  pea(g, 200, ph, false, 0.85)
  g.font = "bold 24px sans-serif"
  g.textAlign = "center"
  g.fillStyle = "#ffe27a"
  g.fillText("TT", 100, 24)
  g.fillStyle = "#a5d8ff"
  g.fillText("tt", 200, 24)
}
const hybrid: Draw = (g, ph) => {
  soil(g)
  pea(g, 150, ph, true)
  g.font = "bold 34px sans-serif"
  g.textAlign = "center"
  g.textBaseline = "middle"
  g.fillStyle = "#ffe27a"
  g.fillText("T", 136, 30)
  g.fillStyle = "#a5d8ff"
  g.fillText("t", 164, 30)
}
const gen1: Draw = (g, ph) => {
  soil(g)
  for (let i = 0; i < 4; i++) pea(g, 52 + i * 66, ph + i, true, 0.8)
}
const gen2: Draw = (g, ph) => {
  soil(g)
  for (let i = 0; i < 4; i++) pea(g, 52 + i * 66, ph + i, i !== 3, 0.8)
}

