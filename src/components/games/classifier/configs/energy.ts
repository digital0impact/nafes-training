const thermal: Draw = (g, ph) => {
  bg(g, "#3b0d16", "#16050a")
  for (let i = 0; i < 3; i++) {
    g.strokeStyle = `rgba(255,135,135,${0.5 + 0.3 * Math.sin(ph * 2 + i)})`
    g.lineWidth = 4
    g.beginPath()
    for (let y = 170; y > 40; y -= 4) g.lineTo(110 + i * 40 + Math.sin(y * 0.08 + ph * 3 + i) * 8, y)
    g.stroke()
  }
}
