function ball(g: G, x: number, y: number, r: number, c: string) {
  const grd = g.createRadialGradient(x - r / 3, y - r / 3, 2, x, y, r)
  grd.addColorStop(0, "#fff")
  grd.addColorStop(0.3, c)
  grd.addColorStop(1, "rgba(0,0,0,.4)")
  g.fillStyle = grd
  g.beginPath()
  g.arc(x, y, r, 0, 7)
  g.fill()
}
function label(g: G, t: string, x: number, y: number, c: string, size = 22) {
  g.fillStyle = c
  g.font = `bold ${size}px sans-serif`
  g.textAlign = "center"
  g.textBaseline = "middle"
  g.fillText(t, x, y)
}

/** حركية: كرة تتدحرج مع خطوط سرعة */
const kinetic: Draw = (g, ph) => {
  bg(g, "#3b230d", "#170e05")
  g.fillStyle = "#495057"
  g.fillRect(0, 150, 300, 50)
  const x = 30 + ((ph * 70) % 260)
  g.strokeStyle = "rgba(255,212,59,.6)"
  g.lineWidth = 3
  for (let i = 0; i < 3; i++) {
    g.beginPath()
    g.moveTo(x - 30 - i * 4, 118 + i * 10)
    g.lineTo(x - 60 - i * 10, 118 + i * 10)
    g.stroke()
  }
  ball(g, x, 128, 22, "#fd7e14")
}
