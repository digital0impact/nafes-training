const nuclear: Draw = (g, ph) => {
  bg(g, "#2b1036", "#12061a")
  for (let i = 0; i < 9; i++) {
    const a = i * 2.4
    const r = 8 + (i % 3) * 7
    ball(g, 150 + Math.cos(a) * r, 100 + Math.sin(a) * r, 9, i % 2 ? "#ff6b6b" : "#adb5bd")
  }
  g.strokeStyle = `rgba(229,153,247,${0.4 + 0.3 * Math.sin(ph * 3)})`
  g.lineWidth = 2
  for (let k = 1; k <= 2; k++) {
    g.beginPath()
    g.arc(150, 100, 40 + k * 18 + Math.sin(ph * 2) * 3, 0, 7)
    g.stroke()
  }
}

/** تحولات */
function conv(g: G, ph: number, from: string, to: string, c1: string, c2: string, top: string) {
  bg(g, top, "#0a0f18")
  g.fillStyle = c2
  g.beginPath()
  g.roundRect(20, 70, 100, 60, 12)
  g.fill()
  g.fillStyle = c1
  g.beginPath()
  g.roundRect(180, 70, 100, 60, 12)
  g.fill()
  label(g, to, 70, 100, "#fff", 17)
  label(g, from, 230, 100, "#fff", 17)
  const t = (ph * 0.6) % 1
  g.fillStyle = "#fff"
  g.beginPath()
  g.arc(175 - t * 50, 100, 5, 0, 7)
  g.fill()
}
