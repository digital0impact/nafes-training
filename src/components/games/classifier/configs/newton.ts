function vec(g: G, x1: number, y1: number, x2: number, y2: number, color: string, w = 4) {
  const a = Math.atan2(y2 - y1, x2 - x1)
  g.strokeStyle = color
  g.fillStyle = color
  g.lineWidth = w
  g.beginPath()
  g.moveTo(x1, y1)
  g.lineTo(x2 - 8 * Math.cos(a), y2 - 8 * Math.sin(a))
  g.stroke()
  g.beginPath()
  g.moveTo(x2, y2)
  g.lineTo(x2 - 14 * Math.cos(a - 0.45), y2 - 14 * Math.sin(a - 0.45))
  g.lineTo(x2 - 14 * Math.cos(a + 0.45), y2 - 14 * Math.sin(a + 0.45))
  g.closePath()
  g.fill()
}

function label(g: G, text: string, x: number, y: number, color = "#fff", size = 15) {
  g.fillStyle = color
  g.font = `bold ${size}px sans-serif`
  g.textAlign = "center"
  g.textBaseline = "middle"
  g.fillText(text, x, y)
}

function box(g: G, x: number, y: number, w: number, h: number, color: string) {
  g.fillStyle = color
  g.beginPath()
  g.roundRect(x, y, w, h, 6)
  g.fill()
  g.strokeStyle = "rgba(0,0,0,.3)"
  g.lineWidth = 2
  g.strokeRect(x + 6, y + 6, w - 12, h - 12)
}

function ground(g: G, y = 150) {
  g.fillStyle = "#495057"
  g.fillRect(0, y, 300, 50)
}

