/** الكميات الكهربائية */
function meter(g: G, ph: number, letter: string, color: string, top: string) {
  bg(g, top, "#0a0f18")
  g.fillStyle = "#f1f3f5"
  g.beginPath()
  g.arc(150, 120, 70, Math.PI, 0)
  g.closePath()
  g.fill()
  const a = Math.PI + 0.5 + ((Math.sin(ph) + 1) / 2) * 2.1
  g.strokeStyle = "#c92a2a"
  g.lineWidth = 3
  g.beginPath()
  g.moveTo(150, 118)
  g.lineTo(150 + Math.cos(a) * 60, 118 + Math.sin(a) * 60)
  g.stroke()
  g.direction = "ltr"
  g.fillStyle = color
  g.font = "bold 30px sans-serif"
  g.textAlign = "center"
  g.textBaseline = "middle"
  g.fillText(letter, 150, 160)
  g.direction = "inherit"
}
const current: Draw = (g, ph) => meter(g, ph, "A", "#74c0fc", "#13283f")
const voltage: Draw = (g, ph) => meter(g, ph, "V", "#ffd43b", "#2b2510")
const resistance: Draw = (g, ph) => meter(g, ph, "Ω", "#ff8787", "#3b0d16")
const power: Draw = (g, ph) => meter(g, ph, "W", "#8ce99a", "#0d3b1a")

