function bulb(g: G, x: number, y: number, on: number) {
  const grd = g.createRadialGradient(x, y, 2, x, y, 30)
  grd.addColorStop(0, `rgba(255,236,153,${0.9 * on})`)
  grd.addColorStop(1, "rgba(255,236,153,0)")
  g.fillStyle = grd
  g.beginPath()
  g.arc(x, y, 30, 0, 7)
  g.fill()
  g.fillStyle = on > 0.2 ? "#ffe066" : "#868e96"
  g.beginPath()
  g.arc(x, y, 12, 0, 7)
  g.fill()
  g.fillStyle = "#adb5bd"
  g.fillRect(x - 6, y + 10, 12, 8)
}
function battery(g: G, x: number, y: number) {
  g.fillStyle = "#495057"
  g.fillRect(x - 22, y - 10, 44, 20)
  g.fillStyle = "#fab005"
  g.fillRect(x + 10, y - 10, 12, 20)
  g.fillRect(x + 22, y - 4, 4, 8)
}
function wire(g: G, pts: [number, number][]) {
  g.strokeStyle = "#ced4da"
  g.lineWidth = 3
  g.beginPath()
  pts.forEach(([x, y], i) => (i ? g.lineTo(x, y) : g.moveTo(x, y)))
  g.stroke()
}
function flow(g: G, pts: [number, number][], ph: number, color = "#74c0fc") {
  const segs: number[] = []
  let total = 0
  for (let i = 1; i < pts.length; i++) {
    const d = Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1])
    segs.push(d)
    total += d
  }
  for (let k = 0; k < 10; k++) {
    let s = ((ph * 50 + (k * total) / 10) % total + total) % total
    for (let i = 0; i < segs.length; i++) {
      if (s <= segs[i]) {
        const t = s / segs[i]
        g.fillStyle = color
        g.beginPath()
        g.arc(pts[i][0] + (pts[i + 1][0] - pts[i][0]) * t, pts[i][1] + (pts[i + 1][1] - pts[i][1]) * t, 3, 0, 7)
        g.fill()
        break
      }
      s -= segs[i]
    }
  }
}

const series: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  const path: [number, number][] = [[150, 170], [40, 170], [40, 50], [260, 50], [260, 170], [150, 170]]
  wire(g, path)
  battery(g, 150, 170)
  bulb(g, 110, 50, 0.7)
  bulb(g, 190, 50, 0.7)
  flow(g, path, ph)
}
const parallel: Draw = (g, ph) => {
  bg(g, "#0d3b1a", "#05170a")
  wire(g, [[150, 175], [40, 175], [40, 35], [260, 35], [260, 175], [150, 175]])
  wire(g, [[40, 105], [260, 105]])
  battery(g, 150, 175)
  bulb(g, 150, 35, 1)
  bulb(g, 150, 105, 1)
  flow(g, [[40, 175], [40, 35], [260, 35], [260, 175]], ph, "#8ce99a")
  flow(g, [[40, 105], [260, 105]], ph, "#8ce99a")
}

