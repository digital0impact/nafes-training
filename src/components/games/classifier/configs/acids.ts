/** شريط الرقم الهيدروجيني من صفر إلى ١٤ مع مؤشر على المنطقة المطلوبة */
const PH_COLORS = ["#c92a2a", "#e03131", "#f03e3e", "#fa5252", "#fd7e14", "#fab005", "#fcc419", "#94d82d", "#51cf66", "#20c997", "#15aabf", "#228be6", "#4c6ef5", "#7048e8", "#6741d9"]

function scale(g: G, from: number, to: number, ph: number) {
  for (let i = 0; i <= 14; i++) {
    const x = 18 + i * 18.2
    const on = i >= from && i <= to
    g.globalAlpha = on ? 1 : 0.25
    g.fillStyle = PH_COLORS[i]
    g.fillRect(x, 120, 16, 50)
    g.globalAlpha = 1
    g.fillStyle = on ? "#fff" : "rgba(255,255,255,.4)"
    g.font = "bold 10px sans-serif"
    g.textAlign = "center"
    g.fillText(String(i), x + 8, 184)
  }
  const mid = 18 + ((from + to) / 2) * 18.2 + 8
  g.fillStyle = "#fff"
  g.beginPath()
  g.moveTo(mid, 114 + Math.sin(ph * 4) * 3)
  g.lineTo(mid - 7, 102 + Math.sin(ph * 4) * 3)
  g.lineTo(mid + 7, 102 + Math.sin(ph * 4) * 3)
  g.closePath()
  g.fill()
}

function litmus(g: G, color: string, ph: number) {
  g.strokeStyle = "rgba(255,255,255,.85)"
  g.lineWidth = 3
  g.beginPath()
  g.moveTo(120, 20)
  g.lineTo(120, 92)
  g.lineTo(180, 92)
  g.lineTo(180, 20)
  g.stroke()
  g.fillStyle = "rgba(255,255,255,.15)"
  g.fillRect(122, 46, 56, 44)
  g.fillStyle = color
  g.fillRect(146, 10 + Math.sin(ph * 1.5) * 4, 10, 66)
}

const acid: Draw = (g, ph) => {
  bg(g, "#3b0d16", "#16050a")
  litmus(g, "#e03131", ph)
  scale(g, 0, 6, ph)
}
const neutral: Draw = (g, ph) => {
  bg(g, "#1d3b2a", "#0c1d14")
  litmus(g, "#9775fa", ph)
  scale(g, 7, 7, ph)
}
const base: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  litmus(g, "#4c6ef5", ph)
  scale(g, 8, 14, ph)
}

