function two(g: G, ph: number, top: string, a: string, b: string, dir: number) {
  bg(g, top, "#0a0f18")
  const d = 40 + Math.sin(ph * 1.5) * 10 * dir
  blob(g, 150 - d, 100, 26, a)
  blob(g, 150 + d, 100, 20, b)
}
function arrow(g: G, x1: number, x2: number, y: number, c: string) {
  const s = Math.sign(x2 - x1)
  g.strokeStyle = c
  g.fillStyle = c
  g.lineWidth = 3
  g.beginPath()
  g.moveTo(x1, y)
  g.lineTo(x2 - s * 8, y)
  g.stroke()
  g.beginPath()
  g.moveTo(x2, y)
  g.lineTo(x2 - s * 12, y - 6)
  g.lineTo(x2 - s * 12, y + 6)
  g.closePath()
  g.fill()
}
