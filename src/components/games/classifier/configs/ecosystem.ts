function sun(g: G, x: number, y: number, r: number, ph: number) {
  const grd = g.createRadialGradient(x, y, 2, x, y, r * 1.8)
  grd.addColorStop(0, "#fff3bf")
  grd.addColorStop(0.5, "rgba(255,212,59,.8)")
  grd.addColorStop(1, "rgba(255,212,59,0)")
  g.fillStyle = grd
  g.beginPath()
  g.arc(x, y, r * (1.6 + 0.1 * Math.sin(ph * 2)), 0, 7)
  g.fill()
}
function plant(g: G, x: number, y: number, s: number, ph: number) {
  g.strokeStyle = "#2f9e44"
  g.lineWidth = 3 * s
  g.beginPath()
  g.moveTo(x, y)
  g.lineTo(x, y - 40 * s)
  g.stroke()
  g.fillStyle = "#51cf66"
  for (const d of [-1, 1]) {
    g.beginPath()
    g.ellipse(x + d * 12 * s, y - 25 * s + Math.sin(ph * 2) * 1.5, 12 * s, 5 * s, d * 0.5, 0, 7)
    g.fill()
  }
}
function blob(g: G, x: number, y: number, r: number, c: string) {
  g.fillStyle = c
  g.beginPath()
  g.arc(x, y, r, 0, 7)
  g.fill()
}

