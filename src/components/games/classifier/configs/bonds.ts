function atom(g: G, x: number, y: number, r: number, color: string, label: string) {
  const grd = g.createRadialGradient(x - r / 3, y - r / 3, 2, x, y, r)
  grd.addColorStop(0, "#fff")
  grd.addColorStop(0.35, color)
  grd.addColorStop(1, "rgba(0,0,0,.4)")
  g.fillStyle = grd
  g.beginPath()
  g.arc(x, y, r, 0, 7)
  g.fill()
  g.fillStyle = "#fff"
  g.font = `bold ${Math.round(r * 0.7)}px sans-serif`
  g.textAlign = "center"
  g.textBaseline = "middle"
  g.fillText(label, x, y + 1)
}

function electron(g: G, x: number, y: number, color = "#ffe066") {
  g.fillStyle = color
  g.shadowColor = color
  g.shadowBlur = 8
  g.beginPath()
  g.arc(x, y, 4, 0, 7)
  g.fill()
  g.shadowBlur = 0
}

function shell(g: G, x: number, y: number, r: number) {
  g.strokeStyle = "rgba(255,255,255,.25)"
  g.lineWidth = 1.5
  g.beginPath()
  g.arc(x, y, r, 0, 7)
  g.stroke()
}

/** ذرة صوديوم تنقل إلكترونًا إلى ذرة كلور */
const ionic: Draw = (g, ph) => {
  bg(g, "#3b1d0d", "#170b05")
  shell(g, 90, 100, 48)
  shell(g, 210, 100, 48)
  atom(g, 90, 100, 26, "#fd7e14", "Na")
  atom(g, 210, 100, 30, "#40c057", "Cl")
  const t = (ph * 0.5) % 1
  electron(g, 138 + t * 24, 100 - Math.sin(t * Math.PI) * 40)
  g.fillStyle = "#fff"
  g.font = "bold 18px sans-serif"
  g.fillText("+", 120, 50)
  g.fillText("−", 245, 50)
}

/** أيونات موجبة مرتبة وإلكترونات حرة تتحرك بينها */
const metallic: Draw = (g, ph) => {
  bg(g, "#1d2433", "#0b0f18")
  for (let r = 0; r < 4; r++)
    for (let c = 0; c < 6; c++) atom(g, 50 + c * 40, 40 + r * 40, 13, "#adb5bd", "+")
  for (let i = 0; i < 14; i++) {
    const x = 30 + ((i * 47 + ph * 40) % 240)
    const y = 60 + (i % 3) * 40 + Math.sin(ph * 2 + i) * 8
    electron(g, x, y, "#74c0fc")
  }
}

/** ذرتان تتشاركان زوجًا من الإلكترونات */
const covalent: Draw = (g, ph) => {
  bg(g, "#102a3b", "#06141d")
  g.globalAlpha = 0.35
  shell(g, 120, 100, 50)
  shell(g, 180, 100, 50)
  g.globalAlpha = 1
  atom(g, 120, 100, 26, "#4dabf7", "")
  atom(g, 180, 100, 26, "#4dabf7", "")
  const a = ph * 2
  electron(g, 150 + Math.cos(a) * 6, 92 + Math.sin(a) * 6)
  electron(g, 150 - Math.cos(a) * 6, 108 - Math.sin(a) * 6)
}

/** جزيء الماء: أكسجين سالب جزئيًا وهيدروجين موجب جزئيًا */
const polar: Draw = (g, ph) => {
  bg(g, "#0d2b3b", "#05141d")
  const w = Math.sin(ph) * 3
  atom(g, 150, 85, 34, "#e03131", "O")
  atom(g, 100, 135 + w, 20, "#dee2e6", "H")
  atom(g, 200, 135 - w, 20, "#dee2e6", "H")
  g.direction = "ltr"
  g.fillStyle = "#ffa8a8"
  g.font = "bold 16px sans-serif"
  g.textAlign = "center"
  g.fillText("δ−", 150, 35)
  g.fillStyle = "#a5d8ff"
  g.fillText("δ+", 70, 170)
  g.fillText("δ+", 230, 170)
  g.direction = "inherit"
}

/** جزيء من ذرتين من العنصر نفسه يتشاركان بالتساوي */
const nonpolar: Draw = (g, ph) => {
  bg(g, "#2b2b10", "#141405")
  atom(g, 120, 100, 30, "#fab005", "H")
  atom(g, 180, 100, 30, "#fab005", "H")
  const a = ph * 2
  electron(g, 150, 100 + Math.sin(a) * 12)
  electron(g, 150, 100 - Math.sin(a) * 12)
}

/** ذرة تفقد إلكترونًا */
const lose: Draw = (g, ph) => {
  bg(g, "#3b230d", "#170e05")
  shell(g, 130, 100, 50)
  atom(g, 130, 100, 30, "#fd7e14", "+")
  const t = (ph * 0.4) % 1
  g.globalAlpha = 1 - t
  electron(g, 180 + t * 100, 100 - t * 30)
  g.globalAlpha = 1
}

/** ذرة تكتسب إلكترونًا */
const gain: Draw = (g, ph) => {
  bg(g, "#0d3b1a", "#05170a")
  shell(g, 170, 100, 50)
  atom(g, 170, 100, 30, "#40c057", "−")
  const t = (ph * 0.4) % 1
  g.globalAlpha = Math.min(1, t * 3)
  electron(g, 20 + t * 100, 70 + t * 30)
  g.globalAlpha = 1
}

const share: Draw = covalent

