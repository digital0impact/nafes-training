import { bg } from "../kit"
import type { CardDef, ClassifierConfig, Draw, G } from "../types"

function stage(g: G, x: number, y: number, on: boolean, draw: () => void) {
  g.globalAlpha = on ? 1 : 0.35
  draw()
  g.globalAlpha = 1
  g.strokeStyle = on ? "#fff" : "rgba(255,255,255,.2)"
  g.lineWidth = 2
  g.beginPath()
  g.arc(x, y, 30, 0, 7)
  g.stroke()
}
function egg(g: G, x: number, y: number) {
  g.fillStyle = "#fff3bf"
  g.beginPath()
  g.ellipse(x, y, 8, 11, 0, 0, 7)
  g.fill()
}
function larva(g: G, x: number, y: number) {
  g.fillStyle = "#94d82d"
  for (let i = 0; i < 5; i++) {
    g.beginPath()
    g.arc(x - 14 + i * 7, y + Math.sin(i) * 2, 5, 0, 7)
    g.fill()
  }
}
function pupa(g: G, x: number, y: number) {
  g.fillStyle = "#c08a4b"
  g.beginPath()
  g.ellipse(x, y, 9, 18, 0, 0, 7)
  g.fill()
}
function butterfly(g: G, x: number, y: number, ph: number) {
  const f = 0.6 + 0.4 * Math.abs(Math.sin(ph * 5))
  g.fillStyle = "#ff922b"
  g.beginPath()
  g.ellipse(x - 10 * f, y - 5, 10 * f, 9, -0.4, 0, 7)
  g.ellipse(x + 10 * f, y - 5, 10 * f, 9, 0.4, 0, 7)
  g.fill()
  g.fillStyle = "#212529"
  g.fillRect(x - 1.5, y - 12, 3, 20)
}
function hopper(g: G, x: number, y: number, s: number, wings: boolean) {
  g.fillStyle = "#5c940d"
  g.beginPath()
  g.ellipse(x, y, 16 * s, 6 * s, 0, 0, 7)
  g.fill()
  g.beginPath()
  g.arc(x + 15 * s, y - 2, 5 * s, 0, 7)
  g.fill()
  g.strokeStyle = "#5c940d"
  g.lineWidth = 2
  g.beginPath()
  g.moveTo(x - 4 * s, y + 3)
  g.lineTo(x - 14 * s, y + 12 * s)
  g.lineTo(x - 20 * s, y + 4)
  g.stroke()
  if (wings) {
    g.fillStyle = "rgba(216,245,162,.7)"
    g.beginPath()
    g.ellipse(x - 2, y - 6 * s, 14 * s, 4 * s, -0.2, 0, 7)
    g.fill()
  }
}

/** التحول الكامل: بيضة ← يرقة ← عذراء ← بالغ */
const complete: Draw = (g, ph) => {
  bg(g, "#2b2510", "#141005")
  const k = Math.floor((ph * 0.5) % 4)
  const xs = [255, 185, 115, 45]
  stage(g, xs[0], 100, k === 0, () => egg(g, xs[0], 100))
  stage(g, xs[1], 100, k === 1, () => larva(g, xs[1], 100))
  stage(g, xs[2], 100, k === 2, () => pupa(g, xs[2], 100))
  stage(g, xs[3], 100, k === 3, () => butterfly(g, xs[3], 100, ph))
}
/** التحول الناقص: بيضة ← حورية ← بالغ */
const incomplete: Draw = (g, ph) => {
  bg(g, "#0d3b1a", "#05170a")
  const k = Math.floor((ph * 0.5) % 3)
  const xs = [240, 150, 60]
  stage(g, xs[0], 100, k === 0, () => egg(g, xs[0], 100))
  stage(g, xs[1], 100, k === 1, () => hopper(g, xs[1], 100, 0.7, false))
  stage(g, xs[2], 100, k === 2, () => hopper(g, xs[2], 100, 1, true))
}
/** نمو تدريجي في الحجم */
const gradual: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  const s = 0.6 + 0.4 * ((Math.sin(ph * 0.8) + 1) / 2)
  g.fillStyle = "#e9ecef"
  g.beginPath()
  g.ellipse(150, 120, 40 * s, 30 * s, 0, 0, 7)
  g.fill()
  g.beginPath()
  g.arc(150 + 42 * s, 90, 18 * s, 0, 7)
  g.fill()
  g.fillStyle = "#fab005"
  g.beginPath()
  g.moveTo(150 + 58 * s, 88)
  g.lineTo(150 + 72 * s, 92)
  g.lineTo(150 + 58 * s, 96)
  g.fill()
}

/** إخصاب خارجي: أمشاج كثيرة في الماء */
const external: Draw = (g, ph) => {
  bg(g, "#0d2b3b", "#05141d")
  for (let i = 0; i < 20; i++) {
    const a = Math.sin(i * 12.9898) * 43758.5
    const b = Math.sin(i * 78.233) * 12345.6
    g.fillStyle = "rgba(255,243,191,.9)"
    g.beginPath()
    g.arc(30 + (a - Math.floor(a)) * 240, 40 + (b - Math.floor(b)) * 120 + Math.sin(ph + i) * 3, 5, 0, 7)
    g.fill()
  }
  for (let i = 0; i < 8; i++) {
    const t = (ph * 0.3 + i / 8) % 1
    g.strokeStyle = "#74c0fc"
    g.lineWidth = 2
    const x = 20 + t * 260
    const y = 60 + i * 12
    g.beginPath()
    g.arc(x, y, 3, 0, 7)
    g.moveTo(x - 3, y)
    g.lineTo(x - 12, y + Math.sin(ph * 10 + i) * 3)
    g.stroke()
  }
}
