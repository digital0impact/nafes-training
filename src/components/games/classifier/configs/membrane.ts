/** الغشاء البلازمي أفقي في المنتصف: الأعلى خارج الخلية، الأسفل داخلها */
function wall(g: G, y = 100, gap?: [number, number]) {
  for (let x = 6; x < 300; x += 12) {
    if (gap && x > gap[0] && x < gap[1]) continue
    for (const s of [-1, 1]) {
      g.fillStyle = "#ffc078"
      g.beginPath()
      g.arc(x, y + s * 12, 5, 0, 7)
      g.fill()
      g.strokeStyle = "#e8590c"
      g.lineWidth = 1.5
      g.beginPath()
      g.moveTo(x - 1.5, y + s * 7)
      g.lineTo(x - 1.5, y)
      g.moveTo(x + 1.5, y + s * 7)
      g.lineTo(x + 1.5, y)
      g.stroke()
    }
  }
}
function dot(g: G, x: number, y: number, r: number, c: string) {
  g.fillStyle = c
  g.beginPath()
  g.arc(x, y, r, 0, 7)
  g.fill()
}
/** نقاط ثابتة موزعة شبه عشوائيًا */
function rnd(i: number, s: number) {
  const a = Math.sin(i * 12.9898 + s * 78.233) * 43758.5453
  return a - Math.floor(a)
}

/** انتشار: جزيئات صغيرة تعبر من التركيز العالي إلى المنخفض */
const diffusion: Draw = (g, ph) => {
  bg(g, "#0d3b1a", "#05170a")
  wall(g)
  for (let i = 0; i < 14; i++) dot(g, 15 + rnd(i, 1) * 270, 15 + rnd(i, 2) * 65, 4, "#8ce99a")
  for (let i = 0; i < 4; i++) dot(g, 15 + rnd(i, 3) * 270, 125 + rnd(i, 4) * 65, 4, "#8ce99a")
  for (let k = 0; k < 3; k++) {
    const t = (ph * 0.4 + k / 3) % 1
    dot(g, 70 + k * 80, 60 + t * 90, 4, "#ffe066")
  }
}
/** الخاصية الأسموزية: جزيئات ماء تعبر الغشاء */
const osmosis: Draw = (g, ph) => {
  bg(g, "#0d2b3b", "#05141d")
  wall(g)
  for (let k = 0; k < 5; k++) {
    const t = (ph * 0.35 + k / 5) % 1
    const x = 40 + k * 55
    const y = 150 - t * 110
    dot(g, x, y, 5, "#4dabf7")
    dot(g, x - 4, y - 4, 2.5, "#e9ecef")
    dot(g, x + 4, y - 4, 2.5, "#e9ecef")
  }
}
/** الانتشار المدعوم: جزيء كبير يعبر عبر بروتين ناقل دون طاقة */
function channel(g: G, x: number) {
  g.fillStyle = "#4c6ef5"
  g.beginPath()
  g.roundRect(x - 18, 76, 13, 48, 6)
  g.roundRect(x + 5, 76, 13, 48, 6)
  g.fill()
}
const facilitated: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  wall(g, 100, [130, 170])
  channel(g, 150)
  const t = (ph * 0.35) % 1
  dot(g, 150, 30 + t * 140, 8, "#ffa94d")
}
/** النقل النشط: يعبر من التركيز المنخفض إلى العالي باستهلاك طاقة */
const active: Draw = (g, ph) => {
  bg(g, "#3b0d16", "#16050a")
  wall(g, 100, [130, 170])
  channel(g, 150)
  for (let i = 0; i < 3; i++) dot(g, 30 + rnd(i, 5) * 90, 20 + rnd(i, 6) * 55, 5, "#ff8787")
  for (let i = 0; i < 12; i++) dot(g, 15 + rnd(i, 7) * 270, 130 + rnd(i, 8) * 60, 5, "#ff8787")
  const t = (ph * 0.35) % 1
  dot(g, 150, 30 + t * 140, 6, "#ff8787")
  g.fillStyle = "#ffe066"
  g.beginPath()
  const bx = 205
  const by = 65 + Math.sin(ph * 4) * 3
  g.moveTo(bx, by - 18)
  g.lineTo(bx - 10, by + 2)
  g.lineTo(bx - 1, by + 2)
  g.lineTo(bx - 6, by + 18)
  g.lineTo(bx + 10, by - 4)
  g.lineTo(bx + 1, by - 4)
  g.closePath()
  g.fill()
}
/** البلعمة */
const endo: Draw = (g, ph) => {
  bg(g, "#2b1036", "#12061a")
  const k = (Math.sin(ph) + 1) / 2
  g.fillStyle = "rgba(151,117,250,.35)"
  g.strokeStyle = "#9775fa"
  g.lineWidth = 4
  g.beginPath()
  g.moveTo(10, 130)
  g.lineTo(110, 130)
  g.quadraticCurveTo(105 + 20 * k, 50, 150, 50 + 10 * k)
  g.quadraticCurveTo(195 - 20 * k, 50, 190, 130)
  g.lineTo(290, 130)
  g.lineTo(290, 195)
  g.lineTo(10, 195)
  g.closePath()
  g.fill()
  g.stroke()
  dot(g, 150, 100 - 20 * (1 - k), 16, "#ffd43b")
}
/** الإخراج الخلوي */
const exo: Draw = (g, ph) => {
  bg(g, "#3b230d", "#170e05")
  g.fillStyle = "rgba(255,169,77,.3)"
  g.fillRect(0, 100, 300, 100)
  g.strokeStyle = "#ffa94d"
  g.lineWidth = 4
  g.beginPath()
  g.moveTo(0, 100)
  g.lineTo(300, 100)
  g.stroke()
  const t = (ph * 0.3) % 1
  g.strokeStyle = "#fff"
  g.lineWidth = 2
  g.beginPath()
  g.arc(150, 170 - t * 90, 22, 0, 7)
  g.stroke()
  for (let i = 0; i < 4; i++) dot(g, 142 + (i % 2) * 14, 162 - t * 90 + Math.floor(i / 2) * 14, 4, "#ffe066")
}

