function beaker(g: G, liquid: string, level = 0.6) {
  const x = 100
  const y = 40
  const w = 100
  const h = 130
  g.fillStyle = liquid
  g.fillRect(x + 4, y + h * (1 - level), w - 8, h * level - 4)
  g.strokeStyle = "rgba(255,255,255,.85)"
  g.lineWidth = 3
  g.beginPath()
  g.moveTo(x - 6, y)
  g.lineTo(x, y + 4)
  g.lineTo(x, y + h)
  g.lineTo(x + w, y + h)
  g.lineTo(x + w, y + 4)
  g.lineTo(x + w + 6, y)
  g.stroke()
}

const compound: Draw = (g, ph) => {
  bg(g, "#1b1d2e", "#0d0e18")
  // جزيئات متماثلة: ذرتان مختلفتان متحدتان بنسبة ثابتة
  for (let i = 0; i < 6; i++) {
    const x = 60 + (i % 3) * 90 + Math.sin(ph + i) * 6
    const y = 64 + Math.floor(i / 3) * 70 + Math.cos(ph + i) * 5
    g.fillStyle = "#4dabf7"
    g.beginPath()
    g.arc(x - 9, y, 14, 0, 7)
    g.fill()
    g.fillStyle = "#e9ecef"
    g.beginPath()
    g.arc(x + 12, y, 10, 0, 7)
    g.fill()
  }
}

const homogeneous: Draw = (g, ph) => {
  bg(g, "#13283f", "#0a1626")
  beaker(g, "rgba(255,169,77,.75)")
  // جسيمات موزعة بانتظام
  for (let r = 0; r < 4; r++)
    for (let c = 0; c < 6; c++) {
      g.fillStyle = "rgba(255,255,255,.75)"
      g.beginPath()
      g.arc(114 + c * 14 + Math.sin(ph * 2 + r + c) * 1.5, 104 + r * 15, 2.2, 0, 7)
      g.fill()
    }
}

const heterogeneous: Draw = (g, ph) => {
  bg(g, "#1d3b2a", "#0c1d14")
  // سلطة خضار: قطع غير موزعة بانتظام
  g.fillStyle = "#e9ecef"
  g.beginPath()
  g.ellipse(150, 140, 110, 34, 0, 0, Math.PI)
  g.fill()
  const pieces: [number, number, string, number][] = [
    [100, 128, "#e03131", 12], [130, 136, "#51cf66", 14], [170, 126, "#ffd43b", 9], [196, 138, "#51cf66", 12],
    [150, 120, "#e03131", 10], [118, 118, "#fd7e14", 8], [184, 116, "#2f9e44", 13],
  ]
  pieces.forEach(([x, y, c, r], i) => {
    g.fillStyle = c
    blob(g, x, y + Math.sin(ph + i) * 1.5, r, r * 0.8, ph + i, 1.5, 4)
    g.fill()
  })
}

function solutionState(state: "liquid" | "solid" | "gas"): Draw {
  return (g, ph) => {
    if (state === "liquid") {
      bg(g, "#13283f", "#0a1626")
      beaker(g, "rgba(116,192,252,.6)", 0.65)
      for (let i = 0; i < 6; i++) {
        const t = (ph * 0.35 + i / 6) % 1
        g.strokeStyle = "rgba(255,255,255," + (1 - t) + ")"
        g.lineWidth = 1.5
        g.beginPath()
        g.arc(116 + i * 13, 164 - t * 70, 3, 0, 7)
        g.stroke()
      }
    } else if (state === "solid") {
      bg(g, "#3b2a0d", "#1a1206")
      // سبيكة: شبكة ذرات فلز مع ذرات أخرى
      for (let r = 0; r < 5; r++)
        for (let c = 0; c < 9; c++) {
          const odd = (r * 9 + c) % 5 === 0
          g.fillStyle = odd ? "#adb5bd" : "#e8a33b"
          g.beginPath()
          g.arc(46 + c * 26 + (r % 2) * 13, 48 + r * 26 + Math.sin(ph * 3 + r + c) * 0.8, odd ? 8 : 11, 0, 7)
          g.fill()
        }
    } else {
      bg(g, "#1c4a6e", "#0d2438")
      for (let i = 0; i < 26; i++) {
        const x = (i * 47 + ph * 30 * (1 + (i % 3))) % 300
        const y = 20 + ((i * 61) % 160)
        g.fillStyle = i % 5 === 0 ? "#ff8787" : "#a5d8ff"
        g.beginPath()
        g.arc(x, y, i % 5 === 0 ? 4 : 3, 0, 7)
        g.fill()
      }
    }
  }
}

function satPanel(kind: "solub" | "conc" | "sat" | "unsat" | "super"): Draw {
  return (g, ph) => {
    bg(g, "#1b1d2e", "#0d0e18")
    const level = kind === "conc" ? 0.4 + 0.2 * ((Math.sin(ph) + 1) / 2) : 0.6
    beaker(g, "rgba(116,192,252,.5)", level)
    const n = kind === "unsat" ? 8 : kind === "sat" ? 22 : kind === "super" ? 34 : kind === "conc" ? 16 : 14
    for (let i = 0; i < n; i++) {
      g.fillStyle = "rgba(255,255,255,.85)"
      g.beginPath()
      g.arc(110 + ((i * 37) % 80), 170 - 130 * level + 10 + ((i * 53) % Math.max(10, 130 * level - 18)), 2.2, 0, 7)
      g.fill()
    }
    if (kind === "sat") {
      g.fillStyle = "#e9ecef"
      for (let i = 0; i < 9; i++) g.fillRect(108 + i * 9, 162, 6, 4)
    }
    if (kind === "solub") {
      g.fillStyle = "#ffe27a"
      g.font = "bold 16px sans-serif"
      g.textAlign = "center"
      g.fillText("١٠٠ جم", 150, 28)
    }
    if (kind === "super") {
      g.strokeStyle = "rgba(255,226,122," + (0.5 + 0.5 * Math.sin(ph * 4)) + ")"
      g.lineWidth = 2
      g.strokeRect(96, 36, 108, 138)
    }
  }
}

